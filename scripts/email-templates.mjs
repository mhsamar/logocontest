// Builds src/lib/email/templates.ts from the email designs in Design/emails/*.html (owner, 2026-10-15).
// Run again after a design changes: node scripts/email-templates.mjs
//
// The designs stay the source of layout and text. The only changes made here:
// - the <title> and the hidden preview line come from the catalog (subject and preheader, src/lib/email/catalog.ts);
// - the footer's Unsubscribe link is left out where there is none (codes and security emails always send);
// - optional parts ({{#if}}) around pictures that may be missing, the greeting and the button of notification.html,
//   and the "Checks left" row of logo-check-ready.html;
// - notification.html's body keeps its line breaks and links ({{{body_html}}}, escaped by render());
// - chat-message.html: the entry number only when the chat is about one design;
// - pro-renewal.html: the monthly logo checks come from Admin › Pro plan instead of a fixed 100.
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "Design/emails");
const out = path.join(root, "src/lib/email/templates.ts");

/** Replaces exactly one match, so a changed design fails loudly instead of quietly. */
function swap(html, find, replace, file) {
  const n = typeof find === "string" ? html.split(find).length - 1 : (html.match(new RegExp(find.source, find.flags.includes("g") ? find.flags : find.flags + "g")) ?? []).length;
  if (n !== 1) throw new Error(`${file}: expected one match for ${find}, found ${n}`);
  return html.replace(find, replace);
}

const files = (await readdir(dir)).filter((f) => f.endsWith(".html")).sort();
const entries = [];
for (const file of files) {
  const key = file.replace(/\.html$/, "");
  let html = (await readFile(path.join(dir, file), "utf8")).trim();
  html = swap(html, /<title>[^<]*<\/title>/, "<title>{{subject}}</title>", file);
  html = swap(html, /(<div style="display:none;max-height:0;overflow:hidden;opacity:0;color:transparent">)[^&<]*/, "$1{{preheader}}", file);
  html = swap(html, / &nbsp;·&nbsp; (<a href="\{\{unsubscribe_url\}\}"[^>]*>Unsubscribe<\/a>)/, "{{#if unsubscribe_url}} &nbsp;·&nbsp; $1{{/if}}", file);
  for (const v of ["entry_image_url", "entry_1_image_url", "entry_2_image_url", "entry_3_image_url", "contest_image_url"]) {
    const img = new RegExp(`<img src="\\{\\{${v}\\}\\}"[^>]*>`);
    if (img.test(html)) html = swap(html, img, (m) => `{{#if ${v}}}${m}{{/if}}`, file);
  }
  // The reminder to finish an unpaid contest (owner, 2026-10-26) has the same layout, with its own Unsubscribe.
  if (key === "notification" || key === "contest-reminder") {
    html = swap(html, /(<p [^>]*>Hi \{\{first_name\}\},<\/p>)/, "{{#if first_name}}$1{{/if}}", file);
    html = swap(html, "{{body}}", "{{{body_html}}}", file);
  }
  if (key === "chat-message") html = swap(html, " · entry #{{entry_no}}", "{{#if entry_no}} · entry #{{entry_no}}{{/if}}", file);
  if (key === "pro-renewal") html = swap(html, "{{checks_used}} of 100", "{{checks_used}} of {{checks_limit}}", file);
  if (key === "logo-check-ready") html = swap(html, /(<tr><td [^>]*>Checks left this month<\/td><td [^>]*>\{\{checks_left\}\}<\/td><\/tr>)/, "{{#if checks_left}}$1{{/if}}", file);
  entries.push(`  ${JSON.stringify(key)}: ${JSON.stringify(html)},`);
}

await writeFile(
  out,
  `// Generated by scripts/email-templates.mjs from Design/emails/*.html. Do not edit by hand: change the design and run it again.\n` +
    `import type { EmailKey } from "./catalog";\n\n` +
    `export const TEMPLATES: Record<EmailKey, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`Wrote ${files.length} templates to ${path.relative(root, out)}`);
