## মৌলিকতা, একই রকম লোগো আর মালিকানার প্রশ্ন

- **টেমপ্লেটের ঝুঁকি:** যে আইকনটা নিলেন, অন্য যেকোনো ব্যবসাও ঠিক সেটাই নিতে পারে। ধরুন, মিরপুরের একটা গ্যাজেট পেজ আর চট্টগ্রামের একটা মোবাইলের দোকান, দুটোরই লোগোতে একই ফোনের আইকন। কাস্টমাররা গুলিয়ে ফেলেন, আর কেউই লোগোটাকে পুরোপুরি নিজের বলতে পারেন না। টেমপ্লেটের লাইসেন্সে অনেক সময় একচেটিয়া অধিকার দেওয়া হয় না, তাই ছাপানোর আগে শর্তগুলো পড়ে নিন।
- **AI থেকে একই রকম লোগো:** AI টুল কোনো সতর্কবার্তা ছাড়াই বাজারে আগে থেকে আছে এমন কোনো লোগোর খুব কাছাকাছি কিছু বানিয়ে দিতে পারে। অনেকেই প্রায় একই কথা লিখে লোগো চান ("পাতা + কফির কাপ", "মুকুট + K অক্ষর"), তাই কাছাকাছি ফলাফল আসাটা অস্বাভাবিক নয়।
- **কপিরাইট:** AI দিয়ে বানানো ছবির কপিরাইট নিয়ে নিয়ম দেশভেদে আলাদা, আর এখনো বদলাচ্ছে। কিছু দেশে যে ছবি পুরোটাই AI বানিয়েছে, যাতে মানুষের যথেষ্ট সৃজনশীল অবদান নেই, তা হয়তো কপিরাইট সুরক্ষাই পায় না। সেক্ষেত্রে অন্য কেউ একই রকম লোগো ব্যবহার করলে তাকে আটকানো কঠিন হতে পারে। AI-এর বানানো ছবি কীভাবে ব্যবহার করা যাবে, তা নিয়ে প্রতিটি টুলের শর্তও আলাদা।
- **ট্রেডমার্ক:** পরে লোগোটা ট্রেডমার্ক হিসেবে রেজিস্টার করতে চাইলে, টেমপ্লেটের আইকন বা অন্য কারও লোগোর মতো দেখতে ডিজাইনের কারণে আপত্তি বা বিরোধ দেখা দিতে পারে।

এটি সাধারণ তথ্য, আইনি পরামর্শ নয়। ট্রেডমার্ক করার পরিকল্পনা থাকলে, বা এখন যে লোগো ব্যবহার করছেন তা নিয়ে সন্দেহ থাকলে, একজন আইনজীবী বা ট্রেডমার্ক এজেন্টের সাথে কথা বলে নিন।

## ফাইল, বাংলা লেখা আর পরিবর্তন

### কোন ফাইল হাতে পাবেন

একই লোগোকে ফেসবুকের ছোট্ট প্রোফাইল ছবিতেও ঠিকঠাক দেখাতে হবে, আবার চওড়া সাইনবোর্ডেও। তাই দরকার **ভেক্টর** ফাইল (AI, EPS, SVG আর PDF), যা যেকোনো সাইজে ঝকঝকে থাকে। অনেক AI জেনারেটর দেয় শুধু পিক্সেলের ছবি (PNG বা JPG), যা প্রিন্টের দোকানে বড় করলেই ঝাপসা হয়ে যায়; আসল ভেক্টর ফাইল পেতে হলে সাধারণত লোগোটা কাউকে দিয়ে নতুন করে আঁকাতে হয়। কিছু ফ্রি লোগো মেকার আবার শুধু ছোট একটা PNG দেয়।

