### বাংলা লেখা

আমাদের দেশে অনেক ব্যবসাই নামটা বাংলায় রাখতে চায়, বা বাংলা-ইংরেজি দুটোতেই। AI ইমেজ টুল বাংলা হরফে প্রায়ই হোঁচট খায়: যুক্তাক্ষর ভেঙে যায়, কার-চিহ্ন ভুল জায়গায় বসে, আবার কিছু "অক্ষর" দেখতে বাংলার মতো হলেও আসলে পড়া যায় না। টেমপ্লেট টুলে ভালো বাংলা ফন্টও কম থাকতে পারে। একজন বাংলাদেশি ডিজাইনার এমন লেটারিং আঁকতে পারেন, যা ঠিকঠাক পড়া যায় আর ইংরেজি নামের পাশেও মানিয়ে যায়।

### পরিবর্তন

AI টুলে যত খুশি নতুন করে বানানো যায়, কিন্তু ছোট আর নির্দিষ্ট একটা পরিবর্তন ("পাতাটা একটু বড় করুন, বাকি সব একই রাখুন") করানো কঠিন, কারণ প্রতিবার অন্য জিনিসও বদলে যায়। টেমপ্লেটে মূলত রং, ফন্ট আর আইকন বদলানো যায়। আর ডিজাইনারকে যে পরিবর্তনটা বলবেন, তিনি ঠিক সেটাই করে দিতে পারেন। logocontest.bd-তে চূড়ান্ত ফাইল অনুমোদনের আগে বিজয়ীর কাছে পরিবর্তন চাইতে পারেন, আর কয় দফা চাইবেন তার কোনো নির্দিষ্ট সীমা নেই; শুধু প্রতিবার নতুন ফাইল আসার পর কনটেস্টের নিয়মে দেওয়া সময়ের মধ্যে উত্তর দিতে হয়।

## লোগো মেকার নাকি ডিজাইনার: কখন কোনটা বেছে নেবেন

কুইক টুলই সাধারণত যথেষ্ট, যখন:

- একটা আইডিয়া যাচাই করছেন, যেমন শীতে ঘরে বানানো পিঠার পেজ বা ঈদের আগে আচারের অর্ডার, আর ব্যবসাটা টিকবে কিনা এখনো জানেন না।
- অল্প দিনের জন্য কিছু লাগবে, যেমন পহেলা বৈশাখের মেলায় একটা স্টল।
- ব্রিফ লেখার আগে নিজে একটু দেখে নিতে চান কোন স্টাইল আর রং ভালো লাগে।

ডিজাইনার দিয়ে লোগো করান, যখন:

- লোগো যাবে সাইনবোর্ড, প্যাকেট, শপিং ব্যাগ, টি-শার্ট বা ডেলিভারি বক্সে।
- নাম বাংলায়, বা বাংলা আর ইংরেজি দুটোতেই।
- স্টক কেনা, দোকান সাজানো বা বিজ্ঞাপনে ভালো অঙ্কের টাকা ঢালছেন।
- ভবিষ্যতে ট্রেডমার্ক করাতে বা নতুন শাখা খুলতে চান।
- প্রতিযোগীদের থেকে আলাদা হতে চান। logocontest.bd-এর ব্রিফে প্রতিযোগীদের নাম বা লিংক দিতে পারেন, যাতে ডিজাইনাররা খেয়াল রাখেন আপনার লোগো যেন তাদের মতো না দেখায়।

অনেক এফ-কমার্স সেলারের জন্য একটা বাস্তব পথ: যাচাইয়ের সময়টায় সাদামাটা একটা অস্থায়ী লোগো দিয়ে চালান। অর্ডার আর বিকাশে পেমেন্ট নিয়মিত আসতে শুরু করলে, সাইনবোর্ড আর প্যাকেট ছাপানোর আগেই একটা ঠিকঠাক লোগো করিয়ে নিন।

## প্রিন্টের আগে লোগোর মিল যাচাই করবেন কীভাবে

লোগো যে-ই বানাক, সাইনবোর্ড বা প্যাকেট ছাপাতে টাকা খরচের আগে একবার যাচাই করে নিন। logocontest.bd-এর [AI লোগো চেকার](/logo-checker):

1. ছবি দিয়ে ওয়েবে খুঁজে দেখে, কাছাকাছি দেখতে কোনো লোগো আছে কিনা।
2. logocontest.bd-এর কনটেস্টে পাঠানো লোগোগুলোর সাথে মিলিয়ে দেখে।
3. খুঁজে পাওয়া প্রতিটি লোগোর আকার আপনার লোগোর সাথে একে একে তুলনা করে।
4. ফন্ট দেখে জানায় অক্ষরগুলো কোন ফন্টের মতো (সবসময় ফন্টের নাম বলতে না-ও পারে)।

ফলাফলে তিনটির একটি উত্তর পাবেন: খুব কাছাকাছি কিছু নেই; কিছু মিল আছে, যা পাশাপাশি রেখে দেখা দরকার; অথবা খুব কাছাকাছি লোগো আছে, যা এড়ানো উচিত। ক্লায়েন্টরা নিজের লোগো কনটেস্টের ভেতর থেকে চেক চালান, কনটেস্টে আসা ডিজাইনে বা নিজের আপলোড করা ছবিতে। তাই কুইক টুলে বানানো যে লোগো এখন ব্যবহার করছেন, সেটাও আপলোড করে চেক করা যায়; প্রতিটি আপলোডে ওই কনটেস্টের একটি চেক খরচ হয়। কয়টি চেক পাবেন, তা নির্ভর করে আপনার প্ল্যান আর সাইটের সেটিংসের ওপর। ভালো ফলের জন্য মকআপ নয়, সাদামাটা ব্যাকগ্রাউন্ডে শুধু লোগোটি চেক করুন।

মনে রাখবেন, এটি দেখানো তারিখে তৈরি একটি রিসার্চ রিপোর্ট, আইনি নিশ্চয়তা নয়। যে লোগো অনলাইনে নেই, তা এটি দেখতে পায় না, আর এটি ট্রেডমার্ক সার্চের বিকল্পও নয়।

## logocontest.bd-তে কেন AI দিয়ে বানানো লোগো চলে না

logocontest.bd-এর প্রতিটি লোগো কনটেস্টে লাগবে ১০০% মৌলিক, মানুষের হাতে বানানো কাজ; AI দিয়ে বানানো লোগো এখানে চলে না। ব্রিফে এই দুটি শর্ত সবসময় চালু থাকে, আর কারণগুলোও সোজা:

- **লোগোর মালিক হওয়া:** চূড়ান্ত ফাইল অনুমোদন দিলে পুরো কপিরাইট ডিজাইনারের কাছ থেকে আপনার কাছে চলে আসে। এই প্রতিশ্রুতি টেকে তখনই, যখন কাজটা সত্যিই একজন মানুষের তৈরি।
- **মিলের ঝুঁকি কম:** যে ডিজাইনার আপনার ব্রিফ পড়ে নিজে আঁকেন, তাঁর কাছ থেকে এমন লোগো পাওয়ার সম্ভাবনা অনেক কম, যা একই রকম কথা লিখে অন্য যে কেউ AI থেকে পেয়ে যেতে পারেন।
- **সত্যিকারের ফাইল:** ডিজাইনার লোগোটা ভেক্টর শেপ দিয়ে বানান, তাই ফাইলগুলো সত্যিই এডিট করা যায়।

ডিজাইন পাঠানোর আগে প্রত্যেক ডিজাইনার নিশ্চিত করেন যে লোগোর কোনো অংশ AI দিয়ে বানানো নয় (শুধু মকআপের ব্যাকগ্রাউন্ডে AI চলে)। কোনো ডিজাইন AI দিয়ে বানানো বা কপি মনে হলে ক্লায়েন্ট ও ডিজাইনাররা রিপোর্ট করতে পারেন, আর অ্যাডমিনরা প্রতিটি রিপোর্ট খতিয়ে দেখেন। কপি বা AI দিয়ে বানানো লোগো পাঠালে ডিজাইন সরিয়ে দেওয়া আর স্থায়ী ব্যান পর্যন্ত হতে পারে। চূড়ান্ত ফাইল অনুমোদন না দেওয়া পর্যন্ত আপনার পেমেন্ট জমা থাকে। প্রতিটি ধাপ জানতে দেখুন [কীভাবে কাজ করে](/how-it-works)।

