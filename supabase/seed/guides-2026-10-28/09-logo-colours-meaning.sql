## FAQ

### What is the best colour for a logo?

There is no single best colour. Choose one that fits your business, stands out from competitors and stays readable when small.

### How many colours should a logo have?

Most strong logos use one to three colours: a main colour, a supporting colour and a neutral. Fewer colours make printing cheaper and the logo easier to remember.

### Why does my logo look different in print than on screen?

Screens use light (RGB) and printers use ink (CMYK). Ask for CMYK codes and a test print.

### Can I change my logo colours for Eid or Pohela Boishakh?

You can make festival versions for posts and banners, but keep the main logo the same so people still recognise you.

### Do I have to choose colours before starting a contest?

No. You can tick "Let designers choose" and guide them with ratings and comments as the designs come in.

