## বাংলাদেশের প্রেক্ষাপটে লোগোর রং: পতাকা, উৎসব আর সংস্কৃতি

আমাদের সংস্কৃতিতে কিছু রঙের আলাদা অনুভূতি আছে। লোগোর রং বাছার সময় এগুলো মাথায় রাখুন:

- **সবুজ আর লাল** আমাদের জাতীয় পতাকার রং। দেশপ্রেমের অনুভূতি দেয়, স্বাধীনতা দিবস আর বিজয় দিবসে চারপাশে এই রং। কিন্তু অনেক ব্যবসাই এই জোড়া ব্যবহার করে, তাই লোগো অন্যদের মতো দেখাতে পারে। পতাকা বা অন্য জাতীয় প্রতীক সরাসরি লোগোতে ব্যবহার করতে চাইলে আগে অফিশিয়াল নিয়মটা দেখে নিন।
- **লাল-সাদা** মানেই অনেকের কাছে পহেলা বৈশাখ। মিষ্টির দোকান বা শাড়ির দোকান বৈশাখের পোস্টে এই রং ব্যবহার করতে পারে, স্থায়ী লোগোতে না রেখেও।
- **হলুদ আর কমলা** মনে করায় গায়ে হলুদ আর পহেলা ফাল্গুনের কথা। ইভেন্ট ম্যানেজমেন্ট বা ফুলের দোকানে দারুণ, কিন্তু একটা ক্লিনিকের জন্য একটু বেশি উৎসবমুখর লাগতে পারে।
- **সোনালি, মেরুন আর গাঢ় সবুজ** ঈদ আর বিয়ের মৌসুমে চারপাশে দেখা যায়; গয়না, পোশাক আর গিফট শপে মানায়।
- **সাদা-কালো** পোশাক একুশে ফেব্রুয়ারির শোক আর শ্রদ্ধার সাথে জড়িয়ে আছে, তাই ভারী সাদা-কালো লোগো গম্ভীর অনুভূতি দেয়। তবে ফ্যাশন বা টেক ব্র্যান্ডে কালো লোগো খুব ভালোই চলে।

একটা কাজের কৌশল: লোগোর রং সারা বছর একই রাখুন, আর উৎসবের রং আনুন ফেসবুক পোস্ট, প্যাকেটের স্লিভ বা ব্যানারে। এতে ক্রেতারা আপনাকে চিনতেও পারেন, আবার উৎসবেও শামিল হওয়া যায়।

## কনট্রাস্ট আর পড়া যাওয়া সবার আগে

যে রং দেখতে সুন্দর কিন্তু পড়া যায় না, লোগোর জন্য সেটা খারাপ রং। বেশিরভাগ মানুষ আপনার লোগো প্রথম দেখবেন ছোট আকারে: ফেসবুক কমেন্টের পাশের প্রোফাইল ছবি, ফুড ডেলিভারি অ্যাপের ছোট টাইল, হোয়াটসঅ্যাপ গ্রুপের আইকন। এত ছোট সাইজে শেডের চেয়ে কনট্রাস্ট বেশি জরুরি।

- গাঢ় ব্যাকগ্রাউন্ডে হালকা লেখা, হালকা ব্যাকগ্রাউন্ডে গাঢ় লেখা রাখুন। সাদার ওপর হলুদ লেখা বা হালকা ধূসরের ওপর হালকা সবুজ খুব দ্রুত হারিয়ে যায়।
- লোগোটা সাদা আর গাঢ়, দুই ব্যাকগ্রাউন্ডেই দেখুন। ফেসবুক আর বেশিরভাগ ফোনে ডার্ক মোড আছে, তাই দুই জায়গাতেই লোগো দেখা যাবে।
- সমান উজ্জ্বল দুটো রং পাশাপাশি রাখবেন না, যেমন খাঁটি লালের ওপর খাঁটি সবুজ। কিনারাগুলো যেন কাঁপতে থাকে, লেখা পড়া কঠিন হয়ে যায়।
- কালার ব্লাইন্ডনেসের কথা ভাবুন। লাল আর সবুজ আলাদা করতে না পারাটাই সবচেয়ে সাধারণ ধরন, তাই শুধু লাল বনাম সবুজ দিয়ে লোগোর অংশ আলাদা করবেন না। হালকা আর গাঢ়ের স্পষ্ট পার্থক্য সবার জন্য কাজ করে।
- ওয়েব অ্যাক্সেসিবিলিটি গাইডলাইন (WCAG) সাধারণ লেখার জন্য অন্তত ৪.৫:১ কনট্রাস্ট রেশিওর কথা বলে। লোগো এই নিয়মের বাইরে, তবে লোগোর নিচের ছোট লেখা বা ট্যাগলাইনের জন্য এটা ভালো মাপকাঠি।

### সাদা-কালো টেস্ট

বিজয়ী বাছার আগে ডিজাইনটা সাদার ওপর শুধু কালোতে দেখুন, তারপর কালোর ওপর শুধু সাদায়। রং ছাড়াও যদি আইডিয়াটা কাজ করে, লোগোটা শক্ত। রং সরালেই যদি ভেঙে পড়ে, তাহলে সিল, ক্যাশ মেমো, পত্রিকার বিজ্ঞাপন, এমব্রয়ডারি বা খোদাই করা জিনিসে সমস্যা হবে।

সহজে টেস্ট করার উপায়:

- ফোনের ফটো এডিটরে লোগোটা সাদাকালো (গ্রেস্কেল) করে দেখুন।
- অফিসের সাধারণ প্রিন্টারে প্রিন্ট করুন, বা একটা ফটোকপি করুন।
- থাম্বনেইলের সাইজে ছোট করে হাত লম্বা করে দূর থেকে দেখুন।

logocontest.bd-এর ব্রিফে "এক রঙেও কাজ করে (সাদা-কালো)" শর্ত আর "কালার, সাদা ও কালো ভার্সন" এক্সট্রায় টিক দিতে পারেন। তাহলে বিজয়ী ডিজাইনার নিয়মিত AI, EPS, SVG, PDF, ট্রান্সপারেন্ট PNG আর JPG ফাইলের সাথে হালকা, গাঢ় আর এক রঙের ব্যবহারের জন্য আলাদা ভার্সনও দেবেন।

## লোগো কালার কম্বিনেশন: কেন ১–৩টি রংই যথেষ্ট

ভালো লোগো কালার কম্বিনেশন সাধারণত ছোট হয়:

1. **একটা মূল রং**, যেটা দেখলে মানুষ আপনাকে মনে করবেন।
2. **একটা সাপোর্টিং রং**, যেটা হালকা, গাঢ় বা কনট্রাস্টিং অ্যাকসেন্ট হতে পারে।
3. **একটা নিউট্রাল রং**: কালো, সাদা, ধূসর বা লেখার জন্য একটা গাঢ় শেড।

রং যত বাড়বে, লোগো মনে রাখা তত কঠিন, ছাপানোও তত খরচের। টি-শার্টে স্ক্রিন প্রিন্ট আর প্রিন্টেড শপিং ব্যাগে সাধারণত প্রতিটা বাড়তি রঙে খরচ বাড়ে, আর রাবার স্ট্যাম্প বা এমব্রয়ডারির জন্য এমনিতেই একটা সরল ভার্সন লাগে। গ্রেডিয়েন্ট আর সূক্ষ্ম শেডিং ফোনে সুন্দর লাগে, কিন্তু কম দামি সাইনবোর্ড, এমব্রয়ডারি করা ক্যাপ বা ফটোকপি করা ক্যাশ মেমোতে প্রায়ই নষ্ট হয়ে যায়।

গ্রেডিয়েন্ট পছন্দ হলে একটা ফ্ল্যাট ভার্সনও চেয়ে নিন। শুরু থেকেই পরিষ্কার ডিজাইন চাইলে logocontest.bd-এর ব্রিফে "বাড়তি সাজসজ্জা বা অপ্রয়োজনীয় ইফেক্ট নয় (শ্যাডো, থ্রিডি, ভারী গ্রেডিয়েন্ট)" শর্তে টিক দিতে পারেন।

## স্ক্রিনের রং বনাম ছাপার রং

স্ক্রিন রং বানায় আলো দিয়ে (RGB), আর প্রিন্টার রং বানায় কালি মিশিয়ে (CMYK)। এ কারণেই ঝকঝকে নিয়ন সবুজ বা উজ্জ্বল নীল ভিজিটিং কার্ডে ম্যাড়মেড়ে লাগতে পারে, আর সাইনবোর্ডের লাল ফেসবুক কভারের লালের সাথে মেলে না।

- **HEX আর RGB কোড** স্ক্রিনের জন্য: ফেসবুক, ওয়েবসাইট, অ্যাপ।
- **CMYK ভ্যালু** সাধারণ ছাপার জন্য: কার্ড, লিফলেট, প্যাকেট।
- **Pantone (স্পট কালার)** লাগে যখন প্রেসকে একদম নিখুঁতভাবে রং মেলাতে হয়, যেমন অনেক প্যাকেট একসাথে ছাপার সময়।

ডিজাইনারকে বলুন, যে যে ফরম্যাটে লাগবে সবগুলোর কালার কোড লিখে দিতে। কাগজ আর ম্যাটেরিয়ালও রং বদলায়: একই নীল চকচকে আর্ট কার্ডে, বাদামি ক্রাফট পেপারে আর ভেতরে বাতি জ্বলা ফ্লেক্স সাইনবোর্ডে আলাদা দেখাবে। প্রেসে বড় অর্ডার দেওয়ার আগে একটা টেস্ট প্রিন্ট চেয়ে নিন।

## লোগো কনটেস্টের ব্রিফে রং ঠিক করবেন যেভাবে

[কনটেস্ট শুরু](/start) করলে একটা ধাপে রং বাছতে বলা হয়। হেক্স কোড দিয়ে সর্বোচ্চ ৫টি রং বাছতে পারেন, অথবা নতুন আইডিয়া চাইলে "ডিজাইনাররা বেছে নিক" টিক দিন। কিছু পরামর্শ:

- দোকান, প্যাকেট বা ফেসবুক পেজে আগে থেকেই ব্র্যান্ডের রং থাকলে সেগুলো দিন, যাতে ডিজাইনাররা মিল রাখেন।
- নিশ্চিত না হলে ডিজাইনারদের বাছতে দিন, তারপর স্টার রেটিং আর কমেন্ট দিয়ে পছন্দের রঙের দিকে নিয়ে যান। কনটেস্ট চলার সময় ডিজাইনাররা উন্নত ভার্সন পাঠাতে পারেন।
- "লোগোটি কোথায় ব্যবহার করবেন?" প্রশ্নের উত্তর মন দিয়ে দিন। সাইনবোর্ড আর প্যাকেটের লোগোর রং নিয়ে যেভাবে ভাবতে হয়, শুধু ফেসবুকে থাকা লোগোর বেলায় ঠিক সেভাবে নয়।

ডিজাইন আসতে শুরু করলে পছন্দের লোগোগুলো কনটেস্টের ভেতর থেকেই [AI লোগো চেকার](/logo-checker) দিয়ে চেক করতে পারেন। এটা রঙের স্কোর দেয় (রং বাছাই, কনট্রাস্ট আর লোগো এক রঙে কাজ করে কি না), পড়ার সহজতার স্কোর দেয়, আর ওয়েবে একই রকম দেখতে লোগো খোঁজে। পুরো প্রক্রিয়া জানতে দেখুন [কীভাবে কাজ করে](/how-it-works)।

## প্রশ্নোত্তর

### লোগোর জন্য সবচেয়ে ভালো রং কোনটা?

একক কোনো সেরা রং নেই। এমন রং বাছুন যা আপনার ব্যবসার সাথে মানায়, আশেপাশের প্রতিযোগীদের থেকে আলাদা, আর ছোট সাইজেও পড়া যায়। তারপর সাদা-কালোতে টেস্ট করুন।

### লোগোতে কয়টা রং থাকা উচিত?

বেশিরভাগ ভালো লোগোতে ১ থেকে ৩টি রং থাকে: একটা মূল রং, একটা সাপোর্টিং রং আর একটা নিউট্রাল। রং কম হলে ছাপার খরচ কমে, মনে রাখাও সহজ হয়।

### স্ক্রিনে আর প্রিন্টে লোগোর রং আলাদা লাগে কেন?

স্ক্রিন আলো দিয়ে (RGB) আর প্রিন্টার কালি দিয়ে (CMYK) রং বানায়, কাগজও রং বদলায়। ডিজাইনারের কাছে CMYK কোড চেয়ে নিন, আর বড় অর্ডারের আগে টেস্ট প্রিন্ট করুন।

### ঈদ বা পহেলা বৈশাখে কি লোগোর রং বদলানো যায়?

পোস্ট আর ব্যানারের জন্য উৎসবের ভার্সন বানাতে পারেন, কিন্তু মূল লোগো একই রাখুন, যাতে মানুষ আপনাকে চিনতে পারেন।

