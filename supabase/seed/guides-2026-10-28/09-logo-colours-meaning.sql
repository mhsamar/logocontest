## লোগোর কোন রং কী বোঝায় (তবে চোখ বন্ধ করে বিশ্বাস করবেন না)

রঙের সাথে কিছু অনুভূতি জড়িয়ে থাকে ঠিকই, তবে তা বাঁধাধরা নয়। একই রঙের হালকা আর গাঢ় শেড আলাদা অনুভূতি দেয়, আর আপনার ধরনের ব্যবসার কাছে ক্রেতারা কী আশা করেন, সেটাও বড় ব্যাপার। নিচের তালিকাটা সাধারণ প্রবণতা হিসেবে দেখুন, পাকা নিয়ম হিসেবে নয়:

