DPDT-এর একজন পরীক্ষক আইন আর আগের মার্কগুলোর সাথে মিলিয়ে আবেদনটি দেখেন। লোগোটি আগের কোনো মার্কের খুব কাছাকাছি হলে, বা শুধু পণ্যের বর্ণনা দিলে, আপত্তি আসতে পারে, আর আপনি জবাব দেওয়ার সুযোগ পাবেন।

### ৪. প্রকাশ আর আপত্তি

আবেদন গৃহীত হলে তা অফিসিয়াল ট্রেডমার্কস জার্নালে প্রকাশিত হয়। প্রকাশের পর একটি নির্দিষ্ট সময়ের মধ্যে কেউ যদি মনে করেন মার্কটি তাঁর মার্কের সাথে সাংঘর্ষিক, তিনি আপত্তি (অপোজিশন) জানাতে পারেন। তখন সিদ্ধান্তের আগে দুই পক্ষই নিজেদের যুক্তি তুলে ধরে।

### ৫. রেজিস্ট্রেশন

কেউ আপত্তি না করলে, বা আপত্তির সিদ্ধান্ত আপনার পক্ষে গেলে, মার্কটি রেজিস্টার্ড হয় আর আপনি রেজিস্ট্রেশন সনদ পান। এরপর থেকে লোগোর সাথে ® চিহ্ন ব্যবহার করতে পারবেন।

### ৬. নবায়ন (রিনিউ)

রেজিস্ট্রেশন একটি নির্দিষ্ট মেয়াদের জন্য থাকে, আর মেয়াদ শেষের আগে নবায়ন না করলে তা বাতিল হয়ে যেতে পারে। সনদ হাতে পাওয়ার দিনই ক্যালেন্ডারে নবায়নের তারিখ লিখে রাখুন। বর্তমান মেয়াদ আর নবায়নের নিয়ম DPDT-এর ওয়েবসাইটে দেখে নিন।

## আবেদনের আগে যা গুছিয়ে রাখবেন

- লোগোর যে ভার্সনটি রেজিস্টার করতে চান, তার পরিষ্কার ও চূড়ান্ত ফাইল (শুধু আইকনের ভার্সনের জন্য আলাদা ফাইলিং লাগবে কিনা, এজেন্টকে জিজ্ঞেস করুন)।
- আবেদনকারী বা ব্যবসার সঠিক নাম-ঠিকানা, ট্রেড লাইসেন্স বা কোম্পানির কাগজের সাথে মিল রেখে।
- কী বিক্রি করেন বা কী সেবা দেন, তার পরিষ্কার তালিকা, যাতে সঠিক শ্রেণি বাছা যায়।
- লোগো কোথা থেকে এল তার প্রমাণ: সোর্স ফাইল আর কনটেস্টের রেকর্ড, যেখানে ডিজাইনারের সম্মতি দেওয়া কপিরাইট হস্তান্তরের চুক্তিও আছে।
- লোগো আগে থেকে ব্যবহার করলে প্রথম ব্যবহারের তারিখ আর উদাহরণ, যেমন ক্যাশ মেমো, প্যাকেট বা সাইনবোর্ডের ছবি।

## AI লোগো চেকার কীভাবে সাহায্য করে

বিজয়ী বাছাইয়ের আগে logocontest.bd-এর [AI লোগো চেকার](/logo-checker) আপনার লোগোর সাথে মিল থাকা লোগো খুঁজে দেখে। এটি লোগোটি পড়ে, ছবি দিয়ে ওয়েবে খোঁজে, সাইটের যেকোনো কনটেস্টে পাঠানো প্রতিটি ডিজাইনের সাথে মেলায়, মিল পাওয়া লোগোগুলোর আকার একে একে তুলনা করে, আর অক্ষরগুলো কোন ফন্টের মতো দেখতে তা জানায়। ফলাফলে পাবেন তিনটির একটি পরিষ্কার উত্তর (খুব কাছাকাছি কিছু নেই; কিছু মিল আছে, যা পাশাপাশি রেখে দেখা দরকার; অথবা খুব কাছাকাছি লোগো আছে, যা এড়ানো উচিত), মিল থাকা লোগোগুলো আপনার লোগোর পাশাপাশি, আর যাচাই লিংকসহ একটি PDF সার্টিফিকেট।

ক্লায়েন্টরা নিজের প্রতিটি লোগো কনটেস্টে এটি ফ্রি ব্যবহার করতে পারেন, কনটেস্ট শুরুর দিন থেকে চূড়ান্ত ফাইল পাওয়া পর্যন্ত; কয়টি চেক পাবেন তা পুরস্কারের ওপর নির্ভর করে। ডিজাইনাররাও পাঠানোর আগে নিজের লোগো চেক করতে পারেন।

তবে এটি আসলে কী, তা পরিষ্কার থাকা দরকার: দেখানো তারিখে তৈরি একটি AI রিসার্চ রিপোর্ট। এটি লোগো ১০০% মৌলিক বলে নিশ্চয়তা দিতে পারে না, যে লোগো এখনো অনলাইনে নেই তা দেখতে পায় না, আর DPDT-এর ট্রেডমার্ক সার্চ বা আইনজীবীর বিকল্পও নয়। একে প্রথম ছাঁকনি ভাবুন: সাইনবোর্ড, প্রিন্ট আর ট্রেডমার্ক ফাইলিংয়ে টাকা খরচের আগেই ঝুঁকিপূর্ণ ডিজাইন বাদ দিতে সাহায্য করে।

