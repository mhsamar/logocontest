## Simple habits that protect your brand

- **Use ™ before registration, ® only after.** ™ simply says you treat the logo as your mark. ® means it is registered, so do not use it until you have the certificate.
- **Keep the logo consistent.** Use the same logo on your Facebook page, signboard, packaging and the payment QR stand at your counter. Festive versions for Eid or Pohela Boishakh posts are fine, but keep the registered version as the main one.
- **Watch for copies.** If a page or shop uses a logo very like yours, save dated screenshots first, then get legal advice.

## FAQ

### Do I need a trademark if I already own the logo copyright?

Copyright protects the artwork; a registered trademark protects the logo as your brand in the classes you register. Most businesses benefit from both.

### Can I register a logo that has Bangla text?

Yes, logos with Bangla text are common. The application may ask for a transliteration or translation of the words, so check the current DPDT forms.

### How long does trademark registration take in Bangladesh?

It depends on DPDT's workload and on any objections or oppositions, and can take many months or longer. Ask DPDT or an agent for a current estimate.

