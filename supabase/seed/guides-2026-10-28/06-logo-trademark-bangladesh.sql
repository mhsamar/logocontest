### ১. সার্চ

আবেদনের আগে দেখে নিন একই ধরনের পণ্য বা সেবার জন্য কাছাকাছি কোনো মার্ক আগেই আছে কিনা। অফিসিয়াল রেকর্ড DPDT-তে থাকে, আর ট্রেডমার্ক এজেন্টরা আপনার হয়ে সার্চ করে দিতে পারেন। নাম দিয়ে খুঁজুন, লোগোর চেহারা দিয়েও খুঁজুন। ফেসবুকের একটি পোশাকের পেজ আর একটি রেস্টুরেন্ট আলাদা শ্রেণিতে পড়ে বলে কখনো কখনো কাছাকাছি নাম রাখতে পারে (যদি না কোনোটি সুপরিচিত মার্ক হয়), কিন্তু একই শ্রেণিতে কাছাকাছি মিল থাকলে সেটা বিপদসংকেত।

