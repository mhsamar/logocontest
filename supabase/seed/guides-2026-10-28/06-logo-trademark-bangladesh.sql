## Trademark registration steps in Bangladesh

Details can change, but the path generally looks like this.

### 1. Search

Before applying, check whether a similar mark already exists for similar goods or services. DPDT keeps the official records, and a trademark agent can search for you, by name and by the look of the logo. Similar names can sometimes live side by side in different classes, such as a clothing page and a restaurant (unless one is a well-known mark), but a close match in the same class is a red flag.

### 2. Choose your class and apply

Trademarks are filed for specific classes of goods and services, based on the international (Nice) classification. A tea brand, a beauty salon and a software company would each fall under different classes. The application usually lists the applicant's name and address, a clear image of the logo, the goods or services and their class, and whether the mark is already in use. You can apply yourself or through an agent; the DPDT website explains the current forms and fees.

### 3. Examination

A DPDT examiner checks the application against the law and against earlier marks. If the logo is too close to an existing mark, or only describes the product, you may get an objection and a chance to reply.

### 4. Publication and opposition

If the application is accepted, it is published in the official Trademarks Journal. For a set period after publication, anyone who believes the mark conflicts with theirs can file an opposition, and both sides present their case.

### 5. Registration

If nobody opposes, or the opposition is decided in your favour, the mark is registered and you receive a registration certificate. From then on you can use the ® symbol with that logo.

### 6. Renewal

A registration lasts for a fixed term and must be renewed before it ends, or it can lapse. Note the renewal date the day the certificate arrives; the DPDT website gives the current term.

## What to prepare before you apply

- A clean, final file of the exact logo version you want to register (ask your agent whether an icon-only version needs its own filing).
- The applicant's or business's exact name and address, matching your trade licence or company papers.
- A clear list of what you sell or the services you offer, to pick the right classes.
- Proof of where the logo came from: the source files and your contest records, including the copyright transfer the designer agreed to.
- If you already use the logo, the date of first use and examples, such as cash memos, packaging or photos of your signboard.

