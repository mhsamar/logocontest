- **কপিরাইট** লোগোটিকে একটি শিল্পকর্ম হিসেবে রক্ষা করে: আঁকা, আকার আর অক্ষরের নকশা, ঠিক যেভাবে ডিজাইন করা হয়েছে। সাধারণত যিনি কাজটি তৈরি করেন, প্রথমে কপিরাইট তাঁরই থাকে, যদি না লিখিতভাবে অন্য কাউকে হস্তান্তর করা হয়।
