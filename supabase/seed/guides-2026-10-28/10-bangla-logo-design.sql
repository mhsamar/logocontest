### আমার লোগো বাংলায় হবে, না ইংরেজিতে?

ক্রেতারা বেশিরভাগ স্থানীয় ও বাংলায় পড়েন তো বাংলা, অনলাইনে বা দেশের বাইরে থেকে খোঁজেন তো ইংরেজি, আর দুই ধরনের ক্রেতা থাকলে দুটোই। অনেক ব্যবসা বাংলা আর ইংরেজি দুটো ভার্সনই রাখে।

### লোগোতে কি যেকোনো বাংলা ফন্ট ব্যবহার করা যায়?

শুধু তখনই, যখন ফন্টের লাইসেন্স ব্যবসায়িক বা লোগোতে ব্যবহারের অনুমতি দেয়। ডিজাইনারের কাছে ফন্টের নাম আর লাইসেন্স জেনে নিন, অথবা নিজস্ব লেটারিং চান।

### একই সাইজে বাংলা লেখা ইংরেজির চেয়ে ছোট দেখায় কেন?

মূল অক্ষরের ওপরে-নিচে কার-চিহ্নের জন্য জায়গা রাখতে হয়, তাই অক্ষরগুলো নিজেরা ছোট হয়ে যায়। ডিজাইনাররা চোখে দেখে ভারসাম্য ঠিক করেন।

### ফেসবুকে কি বাংলা লোগো ভালো দেখায়?

হ্যাঁ, যদি ছোট সাইজে টেস্ট করা থাকে। গোল প্রোফাইল ছবির জন্য একটা সরল স্ট্যাকড বা আইকন ভার্সন চেয়ে নিন।

