## লোগো বাংলায়, ইংরেজিতে, না দুটোতেই?

ট্রেন্ড দেখে নয়, ক্রেতা দেখে ঠিক করুন।

- **বাংলা আগে** ভালো কাজ করে যখন ক্রেতারা বেশিরভাগই স্থানীয় আর বাংলা পড়তে স্বচ্ছন্দ: পুরান ঢাকার মিষ্টির দোকান, পাড়ার ফার্মেসি, কোচিং সেন্টার, জেলা শহরের কৃষিপণ্যের দোকান, ঘরোয়া বাঙালি খাবারের রেস্টুরেন্ট, বা বাংলায় পোস্ট দিয়ে বিক্রি করা কোনো এফ-কমার্স পেজ।
- **ইংরেজি আগে** মানায় যখন ক্রেতারা আপনার নাম ইংরেজি অক্ষরে খোঁজেন, টাইপ করেন বা মনে রাখেন: আইটি ফার্ম, রপ্তানি ব্যবসা, অ্যাপ, ইংরেজি নামের পেজ আর ওয়েবসাইট আছে এমন অনলাইন শপ, বা দেশের বাইরের ক্রেতা টার্গেট করা ব্র্যান্ড।
- **দুটোই** বেড়ে ওঠা ব্যবসার জন্য সবচেয়ে সাধারণ উত্তর। সাইনবোর্ড আর প্যাকেটে বাংলা সামনে থাকে, আর ফেসবুক, ওয়েবসাইট ও ডেলিভারি অ্যাপে ইংরেজি। অনেক দোকান একই সাইনবোর্ডে দুটোই রাখে।

একটা বাস্তব কথা: ফেসবুক ইউজারনেম, প্রায় সব ওয়েব অ্যাড্রেস আর বেশিরভাগ অ্যাপ স্টোর ইংরেজি অক্ষরে চলে। লোগো পুরোপুরি বাংলা হলেও নামের একটা ইংরেজি বানান এখনই ঠিক করে ফেলুন (যেমন "Shonar" অথবা "Sonar", দুটো নয়) আর সব জায়গায় সেটাই ব্যবহার করুন।

