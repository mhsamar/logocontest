## Fonts or custom lettering?

There are many Bangla fonts, from free Unicode families such as Hind Siliguri and Noto Sans Bengali to the classic fonts many presses still use. A font is a fine starting point, but most memorable Bangla logos use custom lettering: the designer draws or reshapes each letter so the word has a look of its own.

- **Fonts have licences.** Some are free for commercial use; others need a paid licence. Ask the designer which fonts were used and whether the licence allows use in a logo. On logocontest.bd, the winner's final-files form has a "Font names" box, and you see it as "Fonts" when you review the files. If it is empty, ask in the messages about the files before you approve.
- **Ask for outlined text.** In the vector files (AI, EPS, SVG and PDF), the letters should be converted to shapes, so the logo looks the same on any computer and the print shop does not need the font. This also avoids the old problem of Bangla text breaking when a file made with an older, non-Unicode font is opened somewhere else.

## Pairing a Bangla wordmark with an English one

Two scripts in one logo should feel like one family, not two logos glued together.

- **Match the weight and mood.** A rounded, friendly English font needs a rounded Bangla partner; a sharp, modern English wordmark needs clean, geometric Bangla.
- **Balance the size by eye, not by numbers.** Because of the matra and vowel signs, Bangla set at the same point size usually looks smaller. Adjust until both feel equally important, or make one clearly the main name.
- **Line them up.** Many designers align the Bangla matra with the top of the English letters, or centre both lines on the same axis.
- **Plan two layouts.** Ask for a stacked version (Bangla above English, or the other way round) for square spaces like a profile picture, and a side-by-side version for wide spaces like a signboard or website header.
- **Share one symbol.** If there is an icon, use the same one in both versions.

