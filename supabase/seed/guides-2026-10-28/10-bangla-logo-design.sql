## FAQ

### Should my logo be in Bangla or English?

Bangla if most customers are local, English if they find you online or from abroad, and both if you serve both.

### Can I use any Bangla font in my logo?

Only if its licence allows commercial or logo use. Ask the designer for the font names and licences, or ask for custom lettering.

### Why does Bangla text look smaller than English at the same size?

Vowel signs need space above and below the main letters, so the letters themselves end up smaller. Designers balance this by eye.

### Does a Bangla logo work on Facebook?

Yes, if it is tested at small sizes. Ask for a simple stacked or icon version for the round profile picture.

### Can I get both Bangla and English versions from one contest?

Yes. Write it clearly under "Other requirements", and check that both versions are in the final files before you approve them.

