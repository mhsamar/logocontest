## বাংলা টাইপোগ্রাফি: লোগোতে বাংলা অক্ষর কেন একটু কঠিন

বাংলা লেখা দিয়ে লোগো বানাতে ইংরেজির চেয়ে একটু বেশি যত্ন লাগে। কারণগুলো দেখুন।

### মাত্রা

বেশিরভাগ বাংলা অক্ষর ওপরের একটা আড়াআড়ি রেখা থেকে ঝোলে, এটাই মাত্রা। লোগোতে মাত্রা পুরো শব্দকে একটা শক্ত আকারে বেঁধে দিতে পারে, আর ডিজাইনাররা প্রায়ই এটা নিয়ে খেলেন: লম্বা করেন, মাঝখানে কেটে দেন, বা একটা অংশকে প্রতীক বানিয়ে ফেলেন। বাংলা লোগো টাইপোগ্রাফিতে এটা বড় সুবিধা। কিন্তু মাত্রা খুব পাতলা হলে, বা অনেক জায়গায় ভাঙা হলে, শব্দটা আর বাংলা হিসেবে পড়া যায় না।

### ওপরে-নিচের কার-চিহ্ন

