### যুক্তবর্ণ

ক্ষ, ঙ্গ, ন্ত, ন্দ, ন্ত্র-এর মতো যুক্তবর্ণে দুই বা তিনটি অক্ষর মিলে একটা আকার হয়। সাইনবোর্ডের সাইজে এগুলো দারুণ দেখায়, কিন্তু ফেসবুক কমেন্টের পাশের ছোট্ট প্রোফাইল ছবিতে বা এমব্রয়ডারি করা শার্টে কালো দলা হয়ে যেতে পারে। নামে ভারী যুক্তবর্ণ থাকলে ডিজাইনারদের বলুন অক্ষরের ভেতরের ছোট ফাঁকা জায়গাগুলো খোলা রাখতে আর ছোট করে টেস্ট করতে।

### ক্যালিগ্রাফিক স্টাইল

টানা হাতের ক্যালিগ্রাফিক বাংলা বিয়ের কার্ড বা মিষ্টির বাক্সে অসাধারণ লাগে, কিন্তু সস্তা প্রিন্ট, পত্রিকার বিজ্ঞাপন আর ছোট স্ক্রিনে পাতলা টানগুলো হারিয়ে যায়। এই স্টাইল পছন্দ হলে ছোট সাইজের জন্য একটা মোটা, সরল ভার্সনও চেয়ে নিন।

### ছোট সাইজে পড়া যায় তো?

বেশিরভাগ মানুষ আপনার লোগো প্রথম দেখবেন ছোট আকারে: ফেসবুক প্রোফাইল ছবি, কমেন্ট, হোয়াটসঅ্যাপ চ্যাট, ডেলিভারি অ্যাপের টাইল, দামের ট্যাগ। সিদ্ধান্ত নেওয়ার আগে প্রতিটা বাংলা লোগো সেখানে টেস্ট করুন।

- থাম্বনেইল সাইজে ছোট করে হাত লম্বা করে দেখুন। অচেনা কেউ কি নামটা পড়তে পারবেন?
- এক রঙে, সাদা আর গাঢ় দুই ব্যাকগ্রাউন্ডে দেখুন।
- সবচেয়ে পাতলা টান আর সবচেয়ে ঘন যুক্তবর্ণটা খেয়াল করুন; এগুলোই আগে ভাঙে।
- যিনি কখনো লোগোটা দেখেননি, তাঁকে জোরে পড়তে বলুন।

কনটেস্টের ব্রিফে "ছোট করলেও সহজে পড়া যায়" শর্তে টিক দিতে পারেন। আর কনটেস্টের ভেতর থেকেই [AI লোগো চেকার](/logo-checker) দিয়ে পছন্দের লোগোগুলো চেক করতে পারেন; এটা পড়ার সহজতার স্কোর দেয়, ওয়েবে একই রকম লোগো খোঁজে, আর অনেক সময় অক্ষরগুলো কোন ফন্টের মতো দেখায় তা জানায় (এই অংশটা অনুমান হিসেবেই নিন)।

## ফন্ট, নাকি নিজস্ব লেটারিং?

বাংলা ফন্ট অনেক আছে: Hind Siliguri বা Noto Sans Bengali-এর মতো ফ্রি ইউনিকোড ফন্ট থেকে শুরু করে প্রেসে এখনো চলা পুরোনো ক্লাসিক ফন্ট পর্যন্ত। শুরুর জন্য ফন্ট ঠিক আছে, কিন্তু মনে রাখার মতো বেশিরভাগ বাংলা লোগোতে থাকে নিজস্ব লেটারিং: ডিজাইনার প্রতিটা অক্ষর নিজে আঁকেন বা নতুন করে গড়েন, যাতে শব্দটার নিজের একটা চেহারা হয়। এতে আপনার লোগো পাশের দোকানের সাইনবোর্ডের মতো দেখানোর সম্ভাবনাও কমে।

দুটো জিনিস মনে রাখুন:

- **ফন্টেরও লাইসেন্স আছে।** কিছু ফন্ট ব্যবসায়িক কাজে ফ্রি, কিছুর জন্য টাকা দিয়ে লাইসেন্স কিনতে হয়। ডিজাইনারকে জিজ্ঞেস করুন কোন ফন্ট ব্যবহার হয়েছে আর লোগোতে ব্যবহারের অনুমতি আছে কি না। logocontest.bd-এ বিজয়ী ডিজাইনার ফাইনাল ফাইল পাঠানোর সময় "ফন্টের নাম" লেখার একটা ঘর পান, আর ফাইল দেখার সময় আপনি সেটা "ফন্ট" হিসেবে দেখবেন। ঘরটা খালি থাকলে অ্যাপ্রুভ করার আগে ফাইলের মেসেজে জিজ্ঞেস করে নিন।
- **লেখাকে আউটলাইন করে নিন।** ভেক্টর ফাইলে (AI, EPS, SVG, PDF) অক্ষরগুলো শেপে কনভার্ট করা থাকা উচিত, যাতে যেকোনো কম্পিউটারে লোগো একই রকম দেখায় আর প্রেসে ফন্ট লাগে না। এতে পুরোনো, ইউনিকোড নয় এমন ফন্টে বানানো ফাইল অন্য কম্পিউটারে খুললে বাংলা লেখা ভেঙে যাওয়ার চেনা ঝামেলাটাও থাকে না।

## বাংলা আর ইংরেজি ওয়ার্ডমার্ক একসাথে মেলানো

লোগোতে দুই লিপি থাকলে দুটোকে এক পরিবারের মনে হওয়া চাই, আঠা দিয়ে জোড়া লাগানো দুটো আলাদা লোগো নয়।

- **ওজন আর মেজাজ মেলান।** গোলগাল, বন্ধুসুলভ ইংরেজি ফন্টের সাথে গোলগাল বাংলা; ধারালো, আধুনিক ইংরেজির সাথে পরিষ্কার, জ্যামিতিক বাংলা।
- **সাইজ চোখে মেলান, সংখ্যায় নয়।** মাত্রা আর কার-চিহ্নের কারণে একই পয়েন্ট সাইজে বাংলা সাধারণত ছোট দেখায়। এমনভাবে ঠিক করুন যাতে দুটো সমান গুরুত্বের মনে হয়, অথবা একটাকে স্পষ্টভাবে মূল নাম বানান।
- **লাইন মেলান।** অনেক ডিজাইনার বাংলার মাত্রাকে ইংরেজি অক্ষরের মাথার সাথে মেলান, বা দুই লাইনকে একই কেন্দ্রে রাখেন।
- **দুটো লেআউট চেয়ে নিন।** প্রোফাইল ছবির মতো চৌকো জায়গার জন্য ওপর-নিচে সাজানো (স্ট্যাকড) ভার্সন, আর সাইনবোর্ড বা ওয়েবসাইট হেডারের মতো চওড়া জায়গার জন্য পাশাপাশি ভার্সন।
- **প্রতীক একটাই রাখুন।** আইকন থাকলে দুই ভার্সনেই একই আইকন রাখুন, যাতে যেকোনো ভাষায় ক্রেতা আপনাকে চিনতে পারেন।

## ডিজাইনারদের কাছে দুই ভার্সন কীভাবে চাইবেন

logocontest.bd-এ ব্রিফ সহজ বাংলা বা ইংরেজিতে লেখা যায়। [কনটেস্ট শুরু](/start) করার সময়:

1. লোগোতে নামটা ঠিক যেভাবে চান, সেভাবেই লোগোর নাম লিখুন: বাংলায়, ইংরেজিতে বা দুটোতেই। বাংলা বানান দুবার মিলিয়ে নিন; একটা ভুল কার-চিহ্ন নামটাই বদলে দেয়।
2. "অন্যান্য শর্ত" ঘরে পরিষ্কার লিখুন কী লাগবে, যেমন: "মূল লোগো বাংলায়, সাথে মিলিয়ে একটা ইংরেজি ভার্সন। দুটোই ওপর-নিচে আর পাশাপাশি সাজানো।" ওই ঘরের "আইডিয়া লাগবে?" তালিকায় বাংলা আর ইংরেজি দুই নাম চাওয়ার একটা তৈরি লাইনও আছে।
3. "ক্যালিগ্রাফিক" বা পছন্দের অন্য স্টাইল বাছুন, আর লোগো ফেসবুক ও প্যাকেটে গেলে "ছোট করলেও সহজে পড়া যায়" টিক দিন।
4. এখনকার সাইনবোর্ডের ছবি বা পছন্দের কোনো উদাহরণ আপলোড করুন। এগুলো শুধু ধারণা দেওয়ার জন্য; ডিজাইনাররা নকল করবেন না।
5. কনটেস্ট চলার সময় স্টার দিয়ে রেটিং আর কমেন্ট করুন, যেমন: "বাংলা লেটারিংটা দারুণ, যুক্তবর্ণটা আরেকটু পরিষ্কার করুন।" ডিজাইনাররা উন্নত ভার্সন পাঠাতে পারেন।

বিজয়ী বাছার পর ডিজাইনার AI, EPS, SVG, PDF, ট্রান্সপারেন্ট PNG ও JPG ফাইল পাঠাবেন, আর আপনি ফাইল অ্যাপ্রুভ করলে পুরো কপিরাইট আপনার হয়ে যায়। যে ভার্সন চেয়েছিলেন সেটা না থাকলে অ্যাপ্রুভ করার আগে "পরিবর্তন চান" বাটন দিয়ে জানান। পুরো ধাপগুলো দেখুন [কীভাবে কাজ করে](/how-it-works) পাতায়।

## বাংলা লোগো নিয়ে কাজ করা ডিজাইনারদের জন্য

বাংলা লেটারিংয়ে হাত ভালো হলে পোর্টফোলিওর স্কিলে সেটা যোগ করুন, যাতে আপনার পাবলিক প্রোফাইলে দেখা যায়। এন্ট্রিতে বাংলা আর ইংরেজি ভার্সন পাশাপাশি দেখান, আর ছোট সাইজের একটা প্রিভিউ দিন, যাতে ক্লায়েন্ট বোঝেন ফোনেও লোগোটা পড়া যাবে। ব্রিফে নাম যে বানানে লেখা, ঠিক সেই বানানই ব্যবহার করুন। এখনো যোগ দেননি? [ডিজাইনার হিসেবে সাইন আপ করুন](/designers/signup)।

