## Logo design tips: a quick test before you approve a logo

Use these logo design tips as a checklist when you compare designs:

1. Shrink it to the size of a fingernail on your phone. Can you still recognise it?
2. Look at it in black only. Does it still work?
3. Put it in a circle, like a Facebook profile picture. Is anything cut off?
4. Show it to three customers for five seconds. Can they describe the main idea?
5. Read the name out loud from the logo alone. Is it clear in Bangla, English or both?
6. Imagine it on your signboard, packet and visiting card. Does it feel right for your customers?
7. Ask yourself whether it would still look good in ten years.
8. Make sure it is original before you start using it.

