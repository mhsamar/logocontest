  $g8$What makes a good logo? A good logo is simple, easy to remember and easy to read, and it still works when it is tiny or printed in one colour. It also fits the business it stands for, stays fresh for years and is completely original. This guide explains the seven qualities of good logo design with Bangladeshi examples, plus logo design tips to judge any logo before you approve it.

## What makes a good logo: start with its job

A logo is not a picture of everything your business does. It is a signature: a small mark that people learn to recognise on your signboard, your Facebook page, your packet or your cash memo. Someone scrolling past your page, or walking past your shop in a busy market, should notice it once and know it the next time.

So good logo design is less about decoration and more about clear decisions. A beautiful logo still fails if nobody can read the name or it blurs on a phone screen.

## Qualities 1 to 3: simple, memorable, and works small

### 1. Simple

Simple logos are easier to recognise, print and remember. Think of the shops along a busy road in Dhaka: the signboards with one clear shape and a bold name are the ones you notice from a rickshaw. The ones with five icons, three fonts and a long slogan become noise.

A simple logo usually has one main shape, one or two fonts and a few colours. Shadows, 3D effects and heavy gradients look impressive on a big screen but often break when printed cheaply on a poly bag or embroidered on a uniform.

### 2. Memorable

A memorable logo has one idea that people can describe in a few words. Try this test: could a customer explain your logo to a friend over the phone? "A green leaf inside the letter B" is easy. "Some lines, a circle and a sort of swirl" is not.

For example, a tea stall that has grown into a small café could use a single cup whose steam forms the first letter of its name. One clear idea beats many average ones.

### 3. Works small and in one colour

Your logo will live in small places: the Facebook profile picture, a browser tab icon, a sticker on a delivery parcel, a seal on a cash memo. If the details disappear at that size, the logo is not doing its job.

It should also work in one colour, black or white only, because many everyday uses allow just one: rubber stamps, thermal-printer receipts, screen-printed jute bags, photocopied leaflets, or a white logo on a dark photo. Test it by printing the logo the size of a coin in black ink. If you can still recognise it, it passes.

Facebook shows a page's profile picture as a circle, so a wide logo with small text at the edges can get cut off. A good designer plans a compact version for spots like this.

## Qualities 4 and 5: fits the business and lasts for years

### 4. Fits the business

A good logo tells people what kind of business you are before they read a word. A children's toy shop can be playful and colourful. A pharmacy or diagnostic centre needs to look clean and trustworthy. A boutique selling handloom sarees might use elegant, traditional details.

Fit also means price level: a kacchi biryani house known for affordable family meals should not look like a five-star hotel. Ask yourself: would my real customers feel this logo is "for them"?

### 5. Timeless

Trends change fast on social media. A logo built on this year's popular effect can look old in two or three years. Timeless logos rely on solid shapes, good letters and balanced colours rather than fashion.

Many old sweet shops in Bangladesh have kept the same simple name style on their signboards for decades, and customers recognise them instantly.

A useful tip: keep festival elements out of your main logo. Use an Eid moon, a summer mango theme or alpana patterns for Pohela Boishakh in posts and special packaging, not in the permanent mark.

## Qualities 6 and 7: a readable name and an original idea

### 6. A readable name

If people cannot read the name, they cannot search for you, tag you or tell a friend. This matters even more in Bangladesh, where many businesses show both a Bangla and an English name. Bangla letters, with their matra (the line along the top) and conjunct letters, need careful font choice and spacing to stay clear at small sizes.

Check the name where it will really be seen: on a signboard across the road, on a phone screen, on a visiting card. Decorative lettering can be beautiful, but if half your customers misread your name, the logo is working against you. If you use both languages, decide which one leads.

### 7. Original

A good logo belongs only to your business. Copying a famous brand, using a free clip-art icon or picking an internet template means other businesses may have the same mark, and it can lead to copyright or trademark problems.

