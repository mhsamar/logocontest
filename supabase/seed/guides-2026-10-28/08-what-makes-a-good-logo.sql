## FAQ

### What is the most important quality of a good logo?

There is no single rule, but simplicity helps most of the others. A simple logo is easier to remember, read and print small or in one colour.

### Do I need both a Bangla and an English name in my logo?

Only if your customers use both. If you include both, decide which one leads and keep each readable when small.

### How many colours should a logo have?

Usually one to three. More colours make printing harder and often costlier, and the logo must still work in one colour.

### Can I use an AI-made or free template logo?

You can, but it may not be unique, and other businesses may be using something very similar. On logocontest.bd, AI-generated logos are not allowed in contests and every design must be original.

