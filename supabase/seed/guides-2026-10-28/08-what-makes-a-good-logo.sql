## গুণ ১ থেকে ৩: সহজ, মনে রাখার মতো, ছোট করলেও কাজ করে

### ১. সহজ

সহজ লোগো তাড়াতাড়ি চেনা যায়, ঝামেলা ছাড়া ছাপানো যায়, মনেও থাকে বেশি। ঢাকার কোনো ব্যস্ত রাস্তার দুই পাশের দোকানগুলোর কথা ভাবুন। রিকশা থেকে যেসব সাইনবোর্ড চোখে পড়ে, সেগুলোতে সাধারণত একটি পরিষ্কার আকার আর মোটা হরফে নাম থাকে। যেখানে পাঁচটা আইকন, তিন রকম ফন্ট আর লম্বা স্লোগান, সেগুলো ভিড়ের মধ্যে হারিয়ে যায়।

সহজ লোগোতে সাধারণত একটি মূল আকার, এক বা দুইটি ফন্ট আর অল্প কয়েকটি রং থাকে। শ্যাডো, থ্রিডি ইফেক্ট বা ভারী গ্রেডিয়েন্ট বড় স্ক্রিনে চমৎকার লাগতে পারে, কিন্তু কম খরচে পলিব্যাগে ছাপালে বা ইউনিফর্মে এমব্রয়ডারি করলে প্রায়ই ঘেঁটে যায়।

### ২. মনে রাখার মতো

মনে রাখার মতো লোগোতে একটাই মূল আইডিয়া থাকে, যা কয়েক শব্দে বলে ফেলা যায়। একটা পরীক্ষা করে দেখুন: কোনো ক্রেতা কি ফোনে বন্ধুকে আপনার লোগোটা বুঝিয়ে বলতে পারবেন? "'ব' অক্ষরের ভেতরে একটা সবুজ পাতা" বলা সহজ। "কিছু দাগ, একটা গোল আর প্যাঁচানো কিছু একটা" বলা কঠিন।

ধরুন, একটা চায়ের দোকান বড় হয়ে ছোট একটি ক্যাফে হয়েছে। তার লোগোতে থাকতে পারে একটি কাপ, যার ধোঁয়া দিয়ে নামের প্রথম অক্ষরটা তৈরি। ফেসবুকে কেক বিক্রি করা কোনো হোম বেকারি একটা কাপকেক বা কেকের এক টুকরো ব্যবহার করতে পারে, নিজের মতো একটু আলাদা ভঙ্গিতে আঁকা। অনেকগুলো সাধারণ আইডিয়ার চেয়ে একটা পরিষ্কার, বুদ্ধিদীপ্ত আইডিয়া অনেক বেশি কাজের।

### ৩. ছোট করলে আর এক রঙেও কাজ করে

আপনার লোগো অনেক ছোট জায়গায় ব্যবহার হবে: কমেন্টের উত্তরের পাশে ফেসবুক প্রোফাইল ছবি, ব্রাউজারের ট্যাবের আইকন, ডেলিভারি পার্সেলের স্টিকার, ক্যাশ মেমোর সিল। ওই সাইজে যদি খুঁটিনাটি হারিয়ে যায়, তাহলে লোগো তার কাজ করছে না।

এক রঙে, মানে শুধু কালো বা শুধু সাদাতেও লোগোটা চলতে হবে। প্রতিদিনের অনেক কাজে একটাই রং ব্যবহার করা যায়: রাবার স্ট্যাম্প, থার্মাল প্রিন্টারের রসিদ, পাটের ব্যাগে স্ক্রিন প্রিন্ট, কোচিং সেন্টারের ফটোকপি করা লিফলেট, কিংবা গাঢ় ছবির ওপর সাদা লোগো। সহজ একটা পরীক্ষা: লোগোটা একটা কয়েনের সমান করে কালো কালিতে প্রিন্ট করুন। তখনও চেনা গেলে লোগো পাস।

আরেকটা কথা মনে রাখুন: ফেসবুক পেজের প্রোফাইল ছবি গোল করে দেখায়। তাই চওড়া লোগোর দুই পাশের ছোট লেখা কেটে যেতে পারে। ভালো ডিজাইনার এসব জায়গার জন্য একটা ছোট, কমপ্যাক্ট ভার্সনও ভেবে রাখেন।

## গুণ ৪ ও ৫: ব্যবসার সাথে মানানসই, আর বহু বছর টিকে থাকে

### ৪. ব্যবসার সাথে মানানসই

ভালো লোগো দেখলে একটা শব্দ পড়ার আগেই মানুষ আঁচ করতে পারে এটা কেমন ব্যবসা। তাই লোগোর অনুভূতি আপনার ক্রেতাদের সাথে মিলতে হবে। বাচ্চাদের খেলনার দোকান মজাদার আর রঙিন হতে পারে। ফার্মেসি বা ডায়াগনস্টিক সেন্টারকে দেখাতে হবে পরিচ্ছন্ন আর ভরসাযোগ্য। আইনজীবীর চেম্বার বা অ্যাকাউন্টিং ফার্মের জন্য সাধারণত শান্ত, গম্ভীর কিছু মানায়। তাঁতের শাড়ির বুটিক হয়তো ঐতিহ্যবাহী নকশার ছোঁয়া চাইবে, আর কম্পিউটার মার্কেটের মোবাইল এক্সেসরিজের দোকান চাইবে ঝকঝকে, আধুনিক কিছু।

দামের স্তরটাও মাথায় রাখুন। যে কাচ্চি বিরিয়ানির দোকান সাশ্রয়ী পারিবারিক খাবারের জায়গা হিসেবে পরিচিত হতে চায়, তার লোগো পাঁচ তারকা হোটেলের মতো দেখালে সাধারণ ক্রেতা ঢুকতে দ্বিধা করতে পারেন। উল্টোটাও সত্যি। লোগো বিচার করার আগে নিজেকে জিজ্ঞেস করুন: আমার আসল ক্রেতারা কি এটা দেখে ভাববেন, "এটা আমাদের জন্য"?

### ৫. বহু বছর টিকে থাকে

সোশ্যাল মিডিয়ায় ট্রেন্ড খুব দ্রুত বদলায়। এ বছরের জনপ্রিয় কোনো ইফেক্টের ওপর ভর করে বানানো লোগো দুই-তিন বছরেই পুরোনো লাগতে পারে। যে লোগো টিকে থাকে, তা দাঁড়িয়ে থাকে শক্ত আকার, ভালো অক্ষর আর ভারসাম্যপূর্ণ রঙের ওপর, ফ্যাশনের ওপর নয়।

দেশের অনেক পুরোনো মিষ্টির দোকান আর পারিবারিক ব্যবসা যুগ যুগ ধরে সাইনবোর্ডে একই সাদামাটা নামের স্টাইল রেখেছে। ক্রেতারা তাদের ভরসা করেন, তার একটা কারণ এই যে চেহারাটা বদলায়নি। একদিন হয়তো লোগো নতুন করে সাজাবেন, কিন্তু ভালো লোগো প্রতি বছর বদলাতে হয় না।

কাজের একটা টিপস: উৎসবের উপাদান মূল লোগোতে রাখবেন না। ঈদের চাঁদ, গরমের আমের থিম বা পহেলা বৈশাখের আলপনা ব্যবহার করুন পোস্ট আর বিশেষ প্যাকেজিংয়ে, স্থায়ী লোগোতে নয়।

## গুণ ৬ ও ৭: নাম সহজে পড়া যায়, আর আইডিয়াটা অরিজিনাল

### ৬. নাম সহজে পড়া যায়

নামই যদি পড়া না যায়, তাহলে মানুষ আপনাকে সার্চ করতে, ট্যাগ করতে বা বন্ধুকে বলতে পারবে না। বাংলাদেশে এটা আরও জরুরি, কারণ অনেক ব্যবসা বাংলা আর ইংরেজি দুই নামই ব্যবহার করে। বাংলা অক্ষরের মাত্রা আর যুক্তাক্ষরের কারণে ছোট সাইজে লেখা পরিষ্কার রাখতে ফন্ট বাছাই আর অক্ষরের মাঝের ফাঁকা জায়গা খুব যত্ন করে ঠিক করতে হয়।

বাস্তব জায়গায় পরীক্ষা করুন: রাস্তার ওপার থেকে সাইনবোর্ডে, ফোনের স্ক্রিনে, ছাপানো ভিজিটিং কার্ডে। সাজানো ক্যালিগ্রাফি দেখতে সুন্দর হতে পারে, কিন্তু অর্ধেক ক্রেতা যদি নামটা ভুল পড়েন, তাহলে লোগো আপনার বিপক্ষে কাজ করছে। দুই ভাষাই লাগলে আগে ঠিক করুন কোনটা প্রধান থাকবে, আর অন্যটাও যেন সহজে পড়া যায়।

