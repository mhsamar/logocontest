## সফটওয়্যার খোলার আগে ব্রিফটা পড়ুন

প্রতিটি কনটেস্টের ব্রিফ একই প্রশ্নগুলো দিয়ে তৈরি, তাই কোথায় কোন ইঙ্গিত থাকে, জেনে রাখুন:

- **ব্যবসার বিবরণ আর কাদের জন্য।** ঢাকার পরিবারগুলোর কাছে মাছ ডেলিভারি দেওয়া একটি ফেসবুক পেজ আর চট্টগ্রামের ছাত্রছাত্রীদের একটি ক্যাফে, দুটোর অনুভূতি একদম আলাদা।
- **লোগোর নাম, স্লোগান আর ক্লায়েন্টের চাওয়া যেকোনো লেখা।** যেভাবে লেখা আছে ঠিক সেভাবেই ব্যবহার করুন, বাংলা বানানসহ। ব্র্যান্ডের নামে একটা অক্ষর ভুল হলেই সবচেয়ে দ্রুত বাদ পড়বেন।
- **স্টাইল আর স্লাইডার।** ক্লায়েন্ট স্টাইল বাছেন (ওয়ার্ডমার্ক, লেটারমার্ক, ছবিভিত্তিক, বিমূর্ত, এমব্লেম, মাসকট, ক্যালিগ্রাফিক) আর তিনটি স্লাইডারে জানান লোগো সাদামাটা না বিস্তারিত, আধুনিক না ক্লাসিক, মজাদার না গম্ভীর হবে। এই পছন্দগুলো মানুন।
- **রং।** দেওয়া রংই ব্যবহার করুন। ক্লায়েন্ট রং বাছার ভার ডিজাইনারদের দিলে, কেন ওই রং নিলেন তা বলুন।
- **লোগো কোথায় ব্যবহার হবে।** ফেসবুক / ইনস্টাগ্রাম, ওয়েবসাইট, সাইনবোর্ড, প্যাকেজিং, প্রিন্ট, মার্চেন্ডাইজ বা টিভি / ভিডিও। ব্যস্ত বাজারের দোকানের সাইনবোর্ডের লোগো রাস্তার ওপার থেকে পড়া যেতে হবে; ফেসবুক প্রোফাইল ছবির লোগো ছোট গোল ফ্রেমের ভেতরেও কাজ করতে হবে।
- **শর্তাবলি।** ক্লায়েন্ট চাইতে পারেন "ছোট করলেও সহজে পড়া যায়", "এক রঙেও কাজ করে", বা শ্যাডো, থ্রিডি আর ভারী গ্রেডিয়েন্ট ছাড়া। এগুলো পরামর্শ নয়, নিয়ম হিসেবে ধরুন।
- **বাড়তি জিনিস।** কিছু ব্রিফে শুধু আইকন, শর্ট লোগো, কালার, সাদা ও কালো ভার্সন, বা অ্যাপ আইকনের সাইজ চাওয়া থাকে। জিতলে এগুলো দিতে হবে, তাই শুরু থেকেই মাথায় রাখুন।
- **উদাহরণ ফাইল আর প্রতিযোগী।** ক্লায়েন্ট যা আপলোড করেছেন আর যে প্রতিযোগীদের নাম দিয়েছেন, সেগুলো দেখুন, যাতে আপনার লোগো ভিড়ে মিশে না গিয়ে আলাদা হয়ে ওঠে।

আঁকার আগে একটি বাক্য লিখে নিন: "এই ব্র্যান্ড ___-এর জন্য, আর এর অনুভূতি হবে ___।" স্কেচ যদি এই বাক্যের সাথে না মেলে, আবার শুরু করুন।

## কম আইডিয়া, কিন্তু শক্ত আইডিয়া

তাড়াহুড়ো করে অনেকগুলো ভার্সন পাঠাতে ইচ্ছে করে। কিন্তু একই আইডিয়ার দশটা রঙিন ভার্সন স্ক্রল করতে করতে ক্লায়েন্ট দ্রুত ক্লান্ত হয়ে পড়েন। ভালোভাবে ভাবা আর সুন্দর করে দেখানো একটি কনসেপ্ট এক গাদা কাঁচা ডিজাইনের চেয়ে বেশি কাজের।

- একটি কনটেস্টে বড়জোর দুই-তিনটি আলাদা দিকের ডিজাইন পাঠান, প্রতিটির পেছনে একটি পরিষ্কার আইডিয়া রেখে।
- একই লোগো পাঁচ রঙে পাঁচটি আলাদা ডিজাইন হিসেবে পাঠাবেন না। রঙের বিকল্পগুলো একটি ডিজাইনের মকআপের ভেতরেই দেখান।
- বেসিক ডিজাইনারদের জন্য একটি কনটেস্টে ডিজাইনের সীমা থাকতে পারে (ডিজাইনার নিয়মাবলিতে বর্তমান নিয়ম দেওয়া আছে), তাই প্রতিটি ডিজাইন যেন কাজে লাগে।
- পরে কোনো ডিজাইন দুর্বল মনে হলে, কনটেস্ট যতক্ষণ ডিজাইন নিচ্ছে ততক্ষণ সেটি তুলে নিতে পারেন।

## সহজ, সৎ মকআপে লোগো দেখান

প্রতিটি ডিজাইনে কয়েকটি মকআপ দেওয়া যায়, আর এর একটিকে আপনি কভার হিসেবে বেছে নেন, যেটি ক্লায়েন্ট সবার আগে দেখেন। কভারে সাদামাটা ব্যাকগ্রাউন্ডে পরিষ্কার লোগোটি রাখুন। বাকি মকআপে দেখান বাস্তবে লোগোটি কেমন দেখাবে:

- পুরো রঙে লোগো, আর এক রঙে (কালো বা সাদা)
- ছোট আকারে, ফেসবুক প্রোফাইল ছবি বা অ্যাপ আইকন হিসেবে
- ব্যবসা অনুযায়ী সাইনবোর্ড, শপিং ব্যাগ, মিষ্টির বাক্স বা টি-শার্টে
- ব্রিফে যা চাওয়া আছে, যেমন ফোনের হোম স্ক্রিনে অ্যাপ আইকন

প্রতিটি মকআপের একটা নাম দিতেই হয়, তাই নামগুলো কাজের রাখুন ("মূল লোগো", "এক রঙে", "সাইনবোর্ড"), যাতে ক্লায়েন্ট বোঝেন কী দেখছেন। মকআপ সহজ রাখুন: মূল আকর্ষণ লোগো, ব্যাকগ্রাউন্ড নয়। AI শুধু মকআপের ব্যাকগ্রাউন্ডে ব্যবহার করা যায়; লোগোটি পুরোপুরি আপনার নিজের কাজ হতে হবে। শুধু নিজের ডিজাইন আর তার মকআপ পাঠান, স্ক্রিনশট বা এলোমেলো ছবি নয়।

## আইডিয়া বুঝিয়ে বলুন, মতামতের দ্রুত জবাব দিন

চল্লিশটা ডিজাইন দেখছেন এমন ক্লায়েন্টের আপনার ডিজাইন মনে রাখার একটা কারণ দরকার। নিজের ডিজাইনে ছোট একটি মন্তব্যে আইডিয়াটা বলুন, যেমন: "K অক্ষরের ভেতরের পাতাটা অর্গানিক চা বোঝায়, আর গোলাকার আকারটা ছোট স্ক্রিনেও লোগোকে বন্ধুসুলভ রাখে।" দুই-তিন লাইনই যথেষ্ট, আর আপনি মন্তব্য করলে ক্লায়েন্টকে জানানো হয়।

তারপর কাছাকাছি থাকুন:

- নোটিফিকেশন চালু রাখুন। ক্লায়েন্ট রেটিং দিলে, মন্তব্য করলে বা শর্টলিস্ট করলে আপনি জানতে পারবেন।
- ভদ্রভাবে জবাব দিন, আর ক্লায়েন্ট পরিবর্তন চাইলে উন্নত ভার্সন পাঠান। আসল শক্তিটা এই রাউন্ডের জন্য জমিয়ে রাখুন: ক্লায়েন্ট দেখতে চান যে ডিজাইনার তাঁর কথা শুনছেন।
- শেষ সময়ের দিকে খেয়াল রাখুন। কনটেস্ট শেষ হওয়ার আগে সাইট ডিজাইনারদের মনে করিয়ে দেয়, তবু সেরা ভার্সনটা শেষ ঘণ্টার জন্য ফেলে রাখবেন না।
- সব কথা সাইটের ভেতরে রাখুন। ডিজাইন, মন্তব্য বা ফাইলে ফোন নম্বর, ইমেইল, সোশ্যাল মিডিয়ার নাম বা লিংক চলবে না। যোগাযোগের তথ্যসহ মন্তব্য পোস্ট হয় না, আর অ্যাকাউন্ট কয়েক ঘণ্টার জন্য সাসপেন্ড হয়।

## মৌলিক থাকুন: কপি নয়, AI দিয়ে তৈরি লোগো নয়

এখানে মৌলিকতা শুধু একটা নিয়ম নয়; ক্লায়েন্টরা কনটেস্টে ভরসা করেন মূলত এই কারণেই। ডিজাইনার নিয়মাবলি একদম পরিষ্কার:

- প্রতিটি ডিজাইন আপনার নিজের হাতে, এই ব্রিফের জন্যই বানানো হতে হবে। অন্য লোগো কপি বা ট্রেস করা, টেমপ্লেট, স্টক আর্টওয়ার্ক, আগে থেকে বানানো বা আবার বিক্রি করা লোগো চলবে না।
- AI দিয়ে তৈরি লোগো চলবে না।
- কোনো ট্রেডমার্ক বা বিখ্যাত ব্র্যান্ডের অংশ ব্যবহার করা যাবে না, আর শুধু সেই ফন্ট ও ছবি ব্যবহার করুন, যেগুলো বাণিজ্যিকভাবে ব্যবহারের অনুমতি আপনার আছে।
- নগ্ন বা যৌন কিছু চলবে না: এমন একটি ডিজাইনেই স্থায়ী ব্যান।

প্রথম ডিজাইনের আগে আপনি নিজের নাম, মোবাইল নম্বর, ঠিকানা আর একটি আইডি নম্বর দিয়ে মৌলিকতার চুক্তিতে সই করেন। ক্লায়েন্ট আর ডিজাইনাররা কোনো ডিজাইনকে কপি বা AI দিয়ে তৈরি বলে রিপোর্ট করতে পারেন, আর অ্যাডমিন প্রতিটি রিপোর্ট যাচাই করেন। কপি করলে জরিমানা বা স্থায়ী ব্যান হতে পারে, আর logocontest.bd আইনি ব্যবস্থা নেয়।

এটাকে নিজের সুবিধায় কাজে লাগান। পাঠানোর আগে [AI লোগো চেকার](/logo-checker) দিয়ে নিজের লোগো চেক করে নিন; ডিজাইনাররা প্রতি মাসে কয়টি চেক পান, তা চেকার পেজে দেখানো আছে। সেরা ফলের জন্য মকআপ নয়, সাদামাটা ব্যাকগ্রাউন্ডে শুধু লোগোটি চেক করুন। খুব কাছাকাছি মিল পেলে ক্লায়েন্ট দেখার আগেই ডিজাইন বদলে ফেলুন।

## বাংলাদেশের লোগো ডিজাইনার হিসেবে প্রোফাইল গড়ুন

জেতা লোগো আপনার পাবলিক প্রোফাইলে দেখা যায়, আর প্রোফাইলে শেয়ার করার মতো একটি QR কোডও আছে।

- একটি পরিষ্কার ছবি বা নিজের মার্ক দিন, আর ছোট একটি বায়োতে লিখুন কোন ধরনের লোগো বানাতে আপনি ভালোবাসেন।
- বিজয় কার্ড তৈরি হলে ডাউনলোড করুন বা ফেসবুকে শেয়ার করুন, যাতে আরও মানুষ আপনার প্রোফাইল খুঁজে পায়।
- জিতলে ঠিকঠাক ডেলিভারি দিন। চূড়ান্ত ফাইল (AI, EPS, SVG, PDF, ট্রান্সপারেন্ট PNG ও JPG), ফন্টের নাম আর ক্লায়েন্টের চাওয়া বাড়তি জিনিস সময়মতো আপলোড করুন। ক্লায়েন্ট কোনো পরিবর্তন চাইলে ফাইল পেজের চ্যাটে জবাব দিয়ে আবার ফাইল পাঠান।
- ক্লায়েন্ট অনুমোদন দিলে, ডিজাইনার নিয়মাবলিতে দেওয়া হোল্ডের দিনগুলো পার হলে ছোট একটি ফি বাদে পুরস্কার আপনার ওয়ালেটে আসে, আর তা বিকাশ বা ব্যাংক অ্যাকাউন্টে তুলতে পারেন। যত বেশি জিতবেন, ফি তত কমবে।

যাঁরা নিয়মিত কনটেস্টে অংশ নেন, তাঁদের জন্য আছে ডিজাইনারদের **প্রো** প্ল্যান। এতে থাকতে পারে প্রো ব্যাজ, হাইলাইট করা ডিজাইন, প্রতি কনটেস্টে বেশি ডিজাইন, ক্লায়েন্টের আমন্ত্রণ, নতুন কনটেস্টে আগে ঢোকার সুযোগ, ক্লায়েন্টের সাথে প্রাইভেট চ্যাট, মাসে বেশি লোগো চেক, আর বিজয়ী বাছাই পর্যন্ত অন্য ডিজাইনারদের কাছ থেকে নিজের ডিজাইন লুকিয়ে রাখার সুবিধা। প্রো এখন চালু আছে কিনা, কী কী পাওয়া যাচ্ছে আর দাম কত, তা সাইটের প্রো পেজে দেখে নিন।

