## Read the brief before you open your design software

Every brief asks the same questions, so learn where the clues are:

- **Business and audience.** A fish delivery page for families in Dhaka needs a different feeling from a café for students in Chattogram.
- **Logo name, slogan and any text the client asks for.** Use them exactly as written, including the Bangla spelling. A wrong letter in the brand name is the fastest way to lose.
- **Styles and sliders.** The client picks styles (wordmark, lettermark, pictorial, abstract, emblem, mascot, calligraphic) and sets three sliders: minimal or complex, modern or classic, playful or serious. Respect those choices.
- **Colours.** Use the colours given. If the client lets designers choose, say why you chose yours.
- **Where the logo will be used.** Facebook / Instagram, website, signboard, packaging, print, merchandise or TV / video. A shop signboard logo in a busy market must read from across the street; a Facebook profile picture logo must still work in a small circle.
- **Requirements.** Clients can ask for things like "easy to read, even when small", "works in one colour" or no shadows, 3D or heavy gradients. Treat these as rules, not suggestions.
- **Extras.** Some briefs ask for an icon-only version, a short logo, colour, white and black versions, or app icon sizes. You deliver them if you win, so plan for them early.
- **Example files and competitors.** Look at what the client uploaded and the competitors they named, so your logo stands apart.

Before you draw, write one sentence: "This brand is for ___ and should feel ___." If your sketch does not match that sentence, start again.

## Send fewer, stronger ideas

Ten versions of the same idea in different colours tire a client fast. One well-thought concept, shown properly, beats a pile of rough ones.

- Send two or three different directions at most, each with a clear idea behind it.
- Do not send the same logo in five colours as five designs. Show colour options as mockups inside one design.
- Basic designers may have a limit on designs per contest (the Designer Rules give the current rule), so make each one count.
- If you later feel a design is weak, you can withdraw it while the contest is still taking designs.

## Show your logo in simple, honest mockups

Each design can carry several mockups, and you choose one as the cover, the picture the client sees first. Make the cover your clean logo on a plain background, then use the others to show the logo in real life:

- the logo in full colour, and in one colour (black or white)
- small, as a Facebook profile picture or an app icon
- on a signboard, a shopping bag, a sweet box or a T-shirt, whichever suits the business
- anything the brief asks for, such as the app icon on a phone home screen

Every mockup needs a name, so make the names useful ("Main logo", "One colour", "Signboard"). Keep mockups simple: the logo is the star, not the background. AI may be used only for mockup backgrounds; the logo itself must be entirely your own work. Send only your design and its mockups, not screenshots or random photos.

## Explain your idea and answer feedback quickly

A client looking at forty designs needs a reason to remember yours. Post a short comment on your own design that explains the idea, such as: "The leaf inside the letter K stands for organic tea, and the rounded shape keeps it friendly on small screens." The client is told when you comment.

Then stay close:

- Keep notifications on. You hear when the client rates your design, comments on it or shortlists it.
- Reply politely and send an improved version when the client asks for changes. Save your best energy for this round: clients want to see that you are listening.
- Watch the end time. The site reminds designers before a contest ends, but do not leave your best version for the last hour.
- Keep every conversation on the site. Phone numbers, emails, social media names and links are not allowed in designs, comments or files. A comment with contact details is not posted, and your account is suspended for some hours.

## Stay original: no copying, no AI-generated logos

Originality is why clients trust a contest. The Designer Rules are clear:

- Every design must be made by you, for this brief. No copying or tracing other logos, and no templates, stock artwork, pre-made or resold logos.
- No AI-generated logos.
- No trademarks or famous brand elements, and only fonts and images you are allowed to use commercially.
- No nude or sexual content: a single such design means a permanent ban.

Before your first design you sign an originality agreement with your name, mobile number, address and an ID number. Clients and designers can report copied or AI-made designs, and admins check every report. Copying can mean a fine or a permanent ban, and logocontest.bd will take legal action.

