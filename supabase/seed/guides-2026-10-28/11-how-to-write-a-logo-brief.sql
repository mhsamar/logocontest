logocontest.bd-তে ফাঁকা পাতায় বসে ব্রিফ লিখতে হয় না। [লোগো কনটেস্ট শুরু করুন](/start/logo) চাপলে একটি ধাপে ধাপে উইজার্ড প্রতিটি অংশ জিজ্ঞেস করে, মোটামুটি এই ক্রমে:

1. **লোগোর নাম:** ব্যবসা বা ব্র্যান্ডের নাম, চাইলে স্লোগান।
2. **ব্যবসা:** ব্যবসার ধরন, ছোট একটা বিবরণ আর টার্গেট অডিয়েন্স, পাশে উদাহরণসহ।
3. **লিংক ও প্রতিযোগী:** ওয়েবসাইট, ফেসবুক, ইনস্টাগ্রাম বা টিকটকের লিংক, আর যেসব ব্যবসা থেকে আলাদা দেখাতে চান।
