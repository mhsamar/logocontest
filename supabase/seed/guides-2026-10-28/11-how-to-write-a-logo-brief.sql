5. **যা লাগবে:** লোগো কোথায় ব্যবহার হবে, বাড়তি কী লাগবে, টিক দেওয়ার মতো শর্ত, অন্যান্য শর্ত, আর উদাহরণ ফাইল বা বর্তমান লোগো (JPG, PNG বা PDF)।
6. **পুরস্কার ও রিভিউ:** পুরস্কার আর কনটেস্টের মেয়াদ বেছে নিন, পুরো ব্রিফ একবার দেখে নিন, তারপর পেমেন্ট।

সাইটে নতুন হলে উইজার্ড আপনার নাম আর যোগাযোগের তথ্যও জেনে নেয়। কোথাও আটকে গেলে কয়েকটি প্রশ্নে তৈরি আইডিয়া পাবেন, ট্যাপ করে বসিয়ে নিজের মতো বদলে নিতে পারবেন। লেখার সাথে সাথে উত্তরগুলো আপনার ডিভাইসে সেভ থাকে। প্রতিটি লোগো কনটেস্টে মূল লোগো (আইকন + নাম) আর AI, EPS, SVG, PDF, ট্রান্সপারেন্ট PNG ও JPG ফাইল সবসময় থাকে। আর দুটি শর্ত সবসময় চালু: ১০০% অরিজিনাল কাজ, যার পূর্ণ কপিরাইট আপনার কাছে হস্তান্তর হবে, আর AI দিয়ে বানানো লোগো চলবে না।

