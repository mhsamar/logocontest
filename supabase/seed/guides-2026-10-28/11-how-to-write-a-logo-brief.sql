## FAQ

### How long should a logo brief be?

Short and clear beats long. A few honest sentences for each question is enough. In the wizard, the business description is kept to 300 characters, so put the most important facts first.

### Can I write my logo brief in Bangla?

Yes. Simple Bangla or English is fine, and the whole site works in both languages.

### What if I don't know which style or colours I want?

Pick the styles that feel closest, set the sliders, and let designers choose the colours. Then use stars and comments on the first designs to show what you like.

### Should I add logos from other brands as references?

Yes, as examples of what you like, with a line about why. Designers must send original work, so references give them a direction, not something to copy.

### Can I change my brief after the contest starts?

Yes. While the contest is open you can edit the brief, and designers who already sent designs are told. Editing the brief does not change the package, prize or contest length.

