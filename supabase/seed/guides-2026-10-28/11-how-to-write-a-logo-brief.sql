## ভালো লোগো ব্রিফ কেন এত জরুরি

ডিজাইনার আপনার মনের কথা জানেন না। আর লোগো কনটেস্টে অনেক ডিজাইনার একই ব্রিফ পড়ে, আপনার সাথে আগে কথা না বলেই কাজ শুরু করেন। তাদের হাতে থাকে শুধু আপনার ব্রিফ। ব্রিফ পরিষ্কার হলে "ঠিক এমনটা চাইনি" বলার ঝামেলা কমে, আর ডিজাইনাররাও আপনার উপযোগী আইডিয়ায় সময় দিতে পারেন।

একই ব্যবসার দুটি ব্রিফ পাশাপাশি দেখুন:

- **দুর্বল ব্রিফ:** "আমার কাপড়ের পেজের জন্য সুন্দর একটা মডার্ন লোগো চাই। অ্যাট্রাকটিভ হতে হবে।"
- **পরিষ্কার ব্রিফ:** "আমরা ফেসবুক পেজে হাতে বানানো সুতির কুর্তি আর থ্রি-পিস বিক্রি করি। ক্রেতা মূলত ঢাকার ২২ থেকে ৩৫ বছর বয়সী চাকরিজীবী নারী। লোগোতে রুচিশীল কিন্তু সাধ্যের মধ্যে, এমন একটা অনুভূতি চাই, খুব দামি বা লাক্সারি নয়। বাংলা আর ইংরেজি দুই নামই রাখবেন, আর গোল প্রোফাইল ছবিতেও যেন পরিষ্কার পড়া যায়।"

দ্বিতীয় ব্রিফ থেকে ডিজাইনার জানছেন ক্রেতা কে, কোন অনুভূতি চাই আর লোগোকে কোথায় কাজ করতে হবে। এর জন্য ডিজাইনের কোনো কঠিন শব্দ লাগেনি। সহজ বাংলা বা ইংরেজি, যেকোনোটায় লিখলেই চলে।

## লোগো ব্রিফ কীভাবে লিখবেন: শুরু করুন ব্যবসা আর ক্রেতাদের দিয়ে

### নাম, শর্ট নাম আর স্লোগান

ডিজাইনাররা যে নাম ব্যবহার করবেন, ঠিক সেই বানানে লিখুন। নামের বাংলা আর ইংরেজি দুই বানানই থাকলে দুটোই দিন। অ্যাপ আইকন বা সিলের জন্য নামের আদ্যক্ষর বা শর্ট নাম লাগলে সেটাও জানান। স্লোগান দিন তখনই, যদি সত্যিই লোগোর ভেতরে চান, কারণ লম্বা ট্যাগলাইন ছোট সাইজে লোগো পড়া কঠিন করে দেয়।

### আপনি কী করেন

দুই-তিন বাক্যে লিখুন কী বিক্রি করেন, কোথায় আর কীভাবে। শুধু "খাবারের ব্যবসা" লেখার চেয়ে "আমরা ঢাকায় ঘরে বানানো আচার বিক্রি করি, বেশিরভাগ ফেসবুকের মাধ্যমে তরুণ পরিবারগুলোর কাছে" অনেক বেশি কাজের। কোন জিনিসটা আপনাকে আলাদা করে, সেটাও বলুন: মায়ের হাতের রেসিপি, শহরের ভেতরে দ্রুত ডেলিভারি, রাজশাহীতে নিজেদের বাগানের আম, কিংবা একই মার্কেটে বিশ বছরের দোকান।

### আপনার ক্রেতা কারা

ডিজাইনাররা আকার, ফন্ট আর রং বাছেন মানুষের কথা ভেবে, তাই সেই মানুষগুলো কারা তা জানান: বয়স, এলাকা, আর তারা আপনাকে কীভাবে খুঁজে পান। SSC আর HSC পরীক্ষার্থীদের কোচিং সেন্টার আর কর্পোরেট আইটি ফার্মের লোগো আলাদা হওয়াই উচিত, দুজনেরই নীল রং পছন্দ হলেও। "মিরপুরের ১৫ থেকে ১৮ বছরের শিক্ষার্থী আর তাদের অভিভাবক", এমন বর্ণনা থেকে ডিজাইনার কাজে লাগানোর মতো তথ্য পান।

## লোগো দেখতে কেমন হবে: স্টাইল, অনুভূতি আর রং

লোগো দেখতে কেমন চান, তা বোঝাতে ডিজাইনার হতে হয় না। তিনটি সহজ উপায়:

- **লোগোর স্টাইল।** শুধু সুন্দর ফন্টে নাম (ওয়ার্ডমার্ক), নামের আদ্যক্ষর (লেটারমার্ক), ছোট একটা ছবি, বিমূর্ত কোনো আকার, ব্যাজের মতো এমব্লেম, মাসকট চরিত্র, নাকি বাংলা ক্যালিগ্রাফি, কোনটা কল্পনা করছেন? একাধিকও পছন্দ হতে পারে।
- **অনুভূতি।** কয়েকটি বিপরীত জোড়ার মধ্যে আপনার ব্র্যান্ড কোথায়, তা ভাবুন: সাদামাটা না বিস্তারিত, আধুনিক না ক্লাসিক, মজাদার না গম্ভীর। খেলনার দোকান হয়তো মজাদার আর রঙিন, কিন্তু ডায়াগনস্টিক সেন্টার হবে পরিচ্ছন্ন আর গম্ভীর।
- **রং।** পেজ, দোকান বা প্যাকেজিংয়ে আগে থেকেই কোনো রং ব্যবহার করলে জানান, পারলে হেক্স কোডসহ (যেমন #0F766E)। নিশ্চিত না হলে রং বাছার দায়িত্ব ডিজাইনারদের দিন। কোনো রং না চাইলে সেটাও বলুন, ধরুন পাশের প্রতিযোগী দোকান ওই রং আগে থেকেই ব্যবহার করে।

প্রতিযোগীদের নামও জানান: আপনার মতো যেসব ব্যবসার সাথে আপনি মিলতে চান না। তাহলে ডিজাইনাররা খেয়াল রাখবেন যেন আপনার লোগো আলাদা দেখায়।

## কী চান, কী চান না, আর রেফারেন্স

এখানে ডিজাইনারদের জন্য আপনার নিয়মগুলো লিখুন। প্রতিটা ছোট আর নির্দিষ্ট রাখুন:

- "রাবার স্ট্যাম্প আর রসিদের জন্য লোগো এক রঙেও চলতে হবে।"
- "ছোট করলেও যেন সহজে পড়া যায়।"
- "শ্যাডো, থ্রিডি বা ভারী গ্রেডিয়েন্ট নয়।"
- "ক্লিপআর্ট বা স্টক আইকন ব্যবহার করবেন না।"
- "বাংলা আর ইংরেজি দুই নামই দেখাবেন।"
- "প্রতিটি আইডিয়া সাইনবোর্ড বা শপিং ব্যাগের মকআপে দেখাবেন।"

রেফারেন্স মানে এমন ছবি, যা দেখে বোঝা যায় আপনার কী ভালো লাগে: কোনো লোগো, প্যাকেজিং, সাইনবোর্ড, এমনকি আপনার দোকানের ছবিও। প্রতিটার কোন দিকটা ভালো লাগে লিখে দিন ("পরিষ্কার অক্ষরগুলো", "উষ্ণ রংগুলো"), যাতে ডিজাইনাররা আইডিয়াটা নেন, ছবিটা নয়। আগে থেকে লোগো থাকলে আর সেটা নতুন করে সাজাতে চাইলে পুরোনোটা দিন, আর বলুন কী রাখবেন আর কী বদলাবেন।

শুধু "ইউনিক", "চোখে পড়ার মতো" বা "প্রফেশনাল" লিখে ছেড়ে দেবেন না। এগুলো সবাই চায়। আপনার ব্যবসার জন্য এর মানে কী, সেটা বুঝিয়ে লিখুন।

## লোগো কোথায় কোথায় ব্যবহার হবে

ল্যাপটপের বড় স্ক্রিনে দারুণ লাগা লোগো সাইনবোর্ডে বা ছোট সিলে গিয়ে ব্যর্থ হতে পারে। তাই যেখানে যেখানে ব্যবহার করবেন, সব জায়গার তালিকা দিন:

- ফেসবুক আর ইনস্টাগ্রাম, যেখানে প্রোফাইল ছবি গোল করে দেখায়
- ওয়েবসাইট বা অনলাইন শপ
- দোকানের সাইনবোর্ড, যা অনেক সময় রাতে রাস্তার ওপার থেকে দেখা হয়
- প্যাকেজিং: বয়ামের লেবেল, বক্স, পলিব্যাগ
- প্রিন্ট: ভিজিটিং কার্ড, প্যাড, ক্যাশ মেমো
- মার্চেন্ডাইজ: টি-শার্ট, ক্যাপ, মগ
- টিভি বা ভিডিও, যেমন ইউটিউবের ইন্ট্রো

কোন বাড়তি ভার্সন লাগবে, সেটাও লিখুন: অ্যাপ বা ওয়েবসাইটের ফেভিকনের জন্য শুধু আইকন, শর্ট নামসহ ছোট লোগো, কিংবা কালার, সাদা আর কালো আলাদা ভার্সন।

