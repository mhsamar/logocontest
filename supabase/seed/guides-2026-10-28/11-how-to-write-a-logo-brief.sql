### লোগো ব্রিফ কত বড় হওয়া উচিত?

লম্বার চেয়ে ছোট আর পরিষ্কার ভালো। প্রতিটি প্রশ্নে কয়েকটা সৎ বাক্যই যথেষ্ট। উইজার্ডে ব্যবসার বিবরণ ৩০০ ক্যারেক্টারের মধ্যে রাখতে হয়, তাই সবচেয়ে জরুরি কথাগুলো আগে লিখুন।

### বাংলায় লোগো ব্রিফ লেখা যাবে?

অবশ্যই। সহজ বাংলা বা ইংরেজি, যেকোনোটায় লিখলেই চলবে, আর পুরো সাইটটাই বাংলা ও ইংরেজি দুই ভাষায় চলে।

### কোন স্টাইল বা রং চাই, বুঝতে না পারলে কী করব?

যে স্টাইলগুলো কাছাকাছি মনে হয় সেগুলো বাছুন, স্লাইডার ঠিক করুন, আর রং ডিজাইনারদের ওপর ছেড়ে দিন। তারপর প্রথম দিকের ডিজাইনে স্টার আর মন্তব্য দিয়ে দেখিয়ে দিন কোনটা ভালো লাগছে।

### অন্য ব্র্যান্ডের লোগো রেফারেন্স হিসেবে দেওয়া যাবে?

হ্যাঁ, কী ভালো লাগে তার উদাহরণ হিসেবে দিন, সাথে এক লাইনে কারণটাও লিখুন। ডিজাইনারদের অরিজিনাল কাজ পাঠাতে হয়, তাই রেফারেন্স তারা দিক বোঝার জন্য ব্যবহার করেন, নকলের জন্য নয়।

