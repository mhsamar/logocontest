  $g11$A logo brief is a short description of your business and the logo you want, written for the designer. Here is how to write a logo brief that works: explain what you do, who your customers are, the style and colours you like, your dos and don'ts, a few references and where the logo will be used. Get these parts right and the logo ideas you receive will fit your business far more often.

## What a good logo brief does

In a logo contest, many designers read the same brief and start work without speaking to you first, so your brief is the only thing they have. A clear brief saves you rounds of "not quite what I meant" and helps designers spend their time on ideas that suit you.

Compare these two briefs for the same business:

- **Weak:** "Need a nice modern logo for my clothing page. Make it attractive."
- **Clear:** "We sell handmade cotton kurtis and three-pieces through our Facebook page, mostly to working women aged 22 to 35 in Dhaka. We want the logo to feel elegant but affordable, not luxury. Please show both the Bangla and the English name, and make sure it reads well as a round profile picture."

The second brief tells designers who the customer is, what feeling to aim for and where the logo must work, with no design jargon.

## Start your logo brief with your business and your customers

### Your name, short name and slogan

Write the exact name designers should use, in the spelling you want, and give both the Bangla and English spellings if you use both. If you want a short form, such as initials for an app icon or a stamp, say so. Add a slogan only if you really want it inside the logo: a long tagline makes a logo harder to read when small.

### What you do

In two or three sentences, describe what you sell, where and how. "We sell homemade pickles in Dhaka, mostly to young families through Facebook" is far more useful than "food business". Mention what makes you different: family recipes, fast delivery inside the city, mangoes from your own orchard in Rajshahi, or twenty years in the same market.

### Who your customers are

Designers choose shapes, fonts and colours for people, so tell them who those people are: their age, their area and how they find you. A coaching centre for SSC and HSC students should look different from a corporate IT firm, even if both like blue. "Students aged 15 to 18 and their parents in Mirpur" gives designers something real to work with.

## Describe the look: style, feel and colours

You do not need to be a designer to describe a look. Three simple tools help:

- **Logo style.** Do you imagine just your name in a nice font (a wordmark), your initials (a lettermark), a small picture, an abstract shape, a badge-like emblem, a mascot character or Bangla calligraphy? You can like more than one.
- **The feel.** Place your brand between a few opposites: minimal or complex, modern or classic, playful or serious.
- **Colours.** If your page, shop or packaging already uses certain colours, share them, ideally with their hex codes (like #0F766E). If you are unsure, it is fine to let designers suggest colours. Say if there is a colour you do not want, for example because a competitor nearby already uses it.

Also name your competitors, businesses like yours that you do not want to look like, so designers can make your logo stand apart.

## Dos, don'ts and references

This is where you give designers your rules. Keep each one short and specific:

- "The logo must work in one colour for our rubber stamp and receipts."
- "Easy to read, even when small."
- "No shadows, 3D or heavy gradients."
- "Please don't use clip art or stock icons."
- "Show both the Bangla and the English name."
- "Please show each idea on a signboard or shopping bag mockup."

References are pictures that show what you like: logos, packaging, signboards or even a photo of your shop. Say what you like about each one ("the clean letters", "the warm colours"), so designers take the idea and not the picture. If you already have a logo and want a refresh, share it and explain what to keep and what to change.

Avoid vague words on their own, such as "unique" or "eye-catching". Everyone wants those; explain what they mean for your business instead.

## Say where the logo will be used

A logo that looks great on a laptop can fail on a signboard or a tiny stamp. List every place you plan to use it:

- Facebook and Instagram, where the profile picture is shown in a circle
- A website or online shop
- A shop signboard, sometimes seen from across the road at night
- Packaging such as jar labels, boxes and poly bags
- Print: visiting cards, letterhead pads and cash memos
- Merchandise: T-shirts, caps and mugs
- TV or video, such as a YouTube intro

Also say which extra versions you need, such as the icon on its own for an app or website favicon, a short logo with your short name, or separate colour, white and black versions.

