- **ক্লাউড কিচেন:** দোকান না থাকায় লোগো থাকবে মূলত ডেলিভারি অ্যাপ, ফেসবুক আর খাবারের বক্সে, তাই মোটা দাগের সহজ একটা আইকন আর ছোট নামই সবচেয়ে দরকারি।
