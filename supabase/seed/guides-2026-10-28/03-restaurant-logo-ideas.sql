একাধিক ধরনের খাবার বিক্রি করলে যেটার জন্য পরিচিত হতে চান, সেটাই বেছে নিন। বিরিয়ানি, বার্গার আর কেক সব একসাথে দেখাতে গেলে লোগোতে কোনোটাই পরিষ্কার হয় না।

