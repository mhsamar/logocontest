## নাম বাংলায়, ইংরেজিতে, নাকি দুটোতেই?

বাংলাদেশে রেস্টুরেন্টের লোগোর জন্য এটা সবচেয়ে বড় সিদ্ধান্তগুলোর একটা, আর এর কোনো একক সঠিক উত্তর নেই।

- **বাংলা হরফ** দেশি, আন্তরিক আর খাঁটি একটা অনুভূতি দেয়। পাড়ার ক্রেতারা সহজে মনে রাখেন, আর ঐতিহ্যবাহী খাবার, মিষ্টি ও পারিবারিক রেস্টুরেন্টে দারুণ মানায়।
- **ইংরেজি হরফ** ডেলিভারি অ্যাপ আর ইনস্টাগ্রামে খুঁজে পেতে সহজ, আর ক্যাফে বা ফাস্ট ফুডে অনেক তরুণ ক্রেতা এটাই আশা করেন।
- **দুটো একসাথে** খুব প্রচলিত: একটা হরফে মূল লোগো আর নিচে ছোট করে অন্যটা, অথবা আলাদা কাজের জন্য আলাদা ভার্সন।

বাংলা বাছলে ডিজাইনারদের বলুন, লোগো ছোট করলেও যুক্তাক্ষরগুলো যেন পরিষ্কার থাকে। নাম বাংলিশে হলে একটা বানান ঠিক করে সাইনবোর্ড থেকে ডেলিভারি অ্যাপের লিস্টিং পর্যন্ত সব জায়গায় সেটাই ব্যবহার করুন।

## সাইনবোর্ড, প্যাকেট আর ডেলিভারি অ্যাপে যেন কাজ করে

রেস্টুরেন্টের লোগোকে অনেক জায়গায় কাজ করতে হয়। ডিজাইনারদের বলুন, লোগোটা যেখানে আসলে ব্যবহার হবে সেখানে কেমন দেখায় তা দেখাতে।

1. **সাইনবোর্ড:** রাস্তার ওপার থেকে, দিনের আলোয় আর রাতে বাতি জ্বললেও যেন পড়া যায়। জোরালো কনট্রাস্ট আর সহজ আকৃতি অ্যাক্রিলিক বা এলইডি অক্ষরে পরিষ্কারভাবে কাটা যায়।
2. **প্যাকেট আর বক্স:** বিরিয়ানির বক্স, কাগজের ব্যাগ, স্টিকার আর কাপের স্লিভ প্রায়ই এক রঙে ছাপা হয়, তাই পরিষ্কার এক রঙের একটা ভার্সন থাকা জরুরি।
3. **ডেলিভারি অ্যাপ আর ফেসবুক:** আপনার লোগো দেখা যায় ছোট্ট চৌকো বা গোল ঘরে, আরও অনেক রেস্টুরেন্টের পাশে। থাম্বনেইলের মতো ছোট আকারেও পড়া যায় এমন একটা শুধু-আইকন ভার্সন বা শর্ট লোগো এখানে সত্যিই পার্থক্য গড়ে দেয়।
4. **উৎসবের পোস্ট:** ইফতার বক্স, ঈদের অফার বা পহেলা বৈশাখের মেনুতে লোগো একই রাখুন, শুধু চারপাশের সাজটা বদলান।

logocontest.bd-তে কনটেস্টের বিজয়ী চূড়ান্ত ফাইল বুঝিয়ে দেন AI, EPS, SVG, PDF, PNG আর JPG ফরম্যাটে। সাইনবোর্ডের দোকান আর ছাপাখানা চায় ভেক্টর ফাইল (AI, EPS, SVG বা PDF); আর PNG ও JPG সরাসরি ফেসবুক আর ডেলিভারি অ্যাপে দেওয়ার জন্য তৈরি।

## রেস্টুরেন্টের লোগোর ব্রিফ কীভাবে লিখবেন

logocontest.bd-তে ব্রিফ মানে কয়েকটা সহজ প্রশ্নের উত্তর, বাংলা বা ইংরেজি যেকোনোটায় লিখলেই চলে।

1. লোগোতে নামটা ঠিক যেভাবে চান, হুবহু সেভাবে **লোগোর নাম** লিখুন (দুই ভাষায় চাইলে দুটোই), আর স্লোগান থাকলে সেটাও যোগ করুন। শর্ট লোগোও চাইলে "যা যা লাগবে"-তে **শর্ট লোগো**-য় টিক দিন, আর ছোট নামটা **অন্যান্য শর্ত** ঘরে লিখে দিন।
2. ব্যবসার ধরন হিসেবে **রেস্টুরেন্ট ও খাবার** বাছুন, তারপর লিখুন কী রান্না করেন আর আপনার ক্রেতা কারা।
3. পছন্দের **স্টাইল** বাছুন, আর স্লাইডারে ঠিক করুন লোগো সাদামাটা না বিস্তারিত, আধুনিক না ক্লাসিক, মজাদার না গম্ভীর হবে।
4. রং বাছুন, অথবা **ডিজাইনাররা বেছে নিক** অপশনে টিক দিন।
5. লোগো কোথায় ব্যবহার হবে তাতে টিক দিন, যেমন **সাইনবোর্ড**, **প্যাকেজিং** আর **ফেসবুক / ইনস্টাগ্রাম**।
6. বাড়তি হিসেবে **শুধু আইকন**, **শর্ট লোগো** বা **কালার, সাদা ও কালো ভার্সন** চাইতে পারেন, আর "ছোট করলেও সহজে পড়া যায়" বা "এক রঙেও কাজ করে (সাদা-কালো)"-এর মতো শর্ত দিতে পারেন।
7. পছন্দের কোনো উদাহরণ বা বর্তমান লোগো থাকলে আপলোড করুন, শুধু ধারণা দেওয়ার জন্য।

কনটেস্ট চলার সময় ডিজাইনে স্টার দিন আর মন্তব্য লিখুন; ডিজাইনাররা উন্নত ভার্সন পাঠাতে পারেন। বিজয়ী বাছার পর চূড়ান্ত ফাইল অনুমোদনের আগে পরিবর্তন চাইতে পারবেন, আর আপনি অনুমোদন করার পরই বিজয়ী টাকা পান। প্রতিটা ধাপ বিস্তারিত জানতে পড়ুন [কীভাবে কাজ করে](/how-it-works), আর এখনকার প্যাকেজ ও মোট খরচ দেখুন [লোগো ডিজাইনের দাম](/logo-design-price) পেজে।

