## FAQ

### What is the best Facebook page logo size?

Upload a square image, for example 1080×1080 px. Facebook shows it much smaller, roughly 170 to 200 px on the page itself and smaller still in the feed, so a larger square keeps it sharp. Check the Facebook Help Centre for the current sizes.

### Why does Facebook cut off my logo?

Because the profile picture is shown as a circle. Anything in the corners of your square image, or touching its edges, gets cut. Keep the logo in the middle with space around it.

### Should my FB page logo be PNG or JPG?

PNG. It keeps logos and text crisp. JPG is fine for photos, but its compression blurs sharp edges.

### Can I use a transparent PNG as my Facebook profile picture?

You can, but a solid background is safer, because transparent areas can look different in light and dark mode. Use your transparent PNG for posts and videos instead.

### Do I need a separate logo for Facebook?

No. You need a version of the same logo: usually the icon or a short logo, placed on a square with a margin. A good designer can make this from your main logo files.

