- অক্ষর বড় রাখুন, কথা কম রাখুন। কভার একটা ব্যানার, লিফলেট নয়।
- লেখা থাকলে PNG-তে সেভ করুন, অক্ষর পরিষ্কার থাকবে।
- ঈদ, পহেলা বৈশাখ বা বড় সেলের সময় কভার বদলান, কিন্তু প্রোফাইল ছবি সারা বছর একই রাখুন। ওই একই গোল ছবি দেখেই মানুষ আপনার পেজ চেনে।

