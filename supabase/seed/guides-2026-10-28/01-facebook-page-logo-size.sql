## Facebook page logo size at a glance

Facebook changes its layouts from time to time, so treat these as working sizes and check the [Facebook Help Centre](https://www.facebook.com/help) for the latest numbers.

- **Profile picture (your logo):** upload a square image. Facebook's Help Centre has given display sizes of roughly 170 to 200 pixels across on computers and phones, and the picture is shown much smaller beside posts, comments and chats. A 1080×1080 px export gives you plenty of sharpness.
- **Shape:** the square is cropped to a circle, so the corners are never seen.
- **Cover photo:** Facebook has said it displays at about 820×312 px on computers and 640×360 px on phones. Many designers work at double the width, for example 1640×624 px, and keep everything important in the centre.
- **File type:** PNG for anything with a logo or text. Facebook's own help pages suggest PNG for profile pictures and cover photos that include a logo or text, because JPG compression blurs sharp edges.

## Why your logo looks small and round on Facebook

Think about where customers actually see your logo. Very few people open your page and look at the big header. Most see a tiny circle next to your page name while they scroll the feed, beside a comment you replied to, in a Messenger chat, or in a notification. At that size, the circle is not much bigger than a fingernail.

Now picture a saree page in Mirpur whose logo is the full shop name in a long, curly script, with a slogan underneath. On a phone, that circle turns into a coloured smudge. A customer who saw the page's Eid collection post yesterday cannot recognise it today, because nothing in the circle is clear enough to remember.

The fix is not a new logo. It is the right **version** of your logo for a small circle: usually the icon on its own, the first letter, or a short name, with bold shapes and few details.

A quick test: shrink your logo on your phone until it is about the size of the picture next to a comment, then hold the phone at arm's length. If you can still tell what it is, it will work on Facebook.

## How to fit your logo inside the circle

1. Start with a square canvas, such as 1080×1080 px.
2. Use the icon or short logo, not the wide logo with the full name and slogan.
3. Leave a comfortable margin on every side, so the circle never cuts a letter or the tip of the icon.
4. Put the logo on a solid background, either your brand colour or white. Transparent backgrounds can look different in light mode and dark mode, so a solid colour is the safer choice for a profile picture.
5. Check it on a real phone, in both light and dark mode, before you publish.
6. Use the same picture on Instagram and WhatsApp Business, which also show profile pictures as circles. Customers recognise you faster when every page looks the same.

## Cover photo: where the logo goes, and where it doesn't

Your profile picture already shows your logo, so the cover does not need a big logo again. Use the cover to say something useful: your new Puja collection, "Home delivery all over Dhaka", "Cash on delivery and bKash", or your opening hours.

- Keep text and any logo in the centre. Phones show the cover in a different shape from computers, and the sides are often cut off.
- On many screens the profile picture sits over, or right next to, the lower-left part of the cover, so keep that corner free of text.
- Use large, short text. A cover is a banner, not a leaflet.
- Save it as PNG if it has text, so the letters stay crisp.
- Change the cover for Eid, Pohela Boishakh or a big sale, but keep the profile picture the same all year. That steady circle is how people recognise your page.

## Common mistakes with Facebook page logos

- **Using the full logo with slogan, phone number and address.** None of it can be read in a small circle.
- **Letters touching the edge.** The circle crop cuts them off.
- **Uploading a screenshot, or a picture forwarded on WhatsApp or Messenger.** These are compressed and come out blurry. Always upload from the original file.
- **Thin lines and tiny details.** They disappear at small sizes.
- **Changing the profile picture with every offer.** Change the cover instead and let the logo stay put.
- **A photo of the shop signboard as the profile picture.** It looks busy, and the actual logo becomes tiny.
- **A free template that many other pages also use.** Customers can mix you up with someone else, and it is hard to call the design your own.

