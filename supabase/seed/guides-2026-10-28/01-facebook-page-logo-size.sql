- **অনেক পেজ যে ফ্রি টেমপ্লেট ব্যবহার করে, সেটাই নেওয়া।** কাস্টমার আপনাকে অন্য কারও সাথে গুলিয়ে ফেলতে পারেন, আর ডিজাইনটাকে পুরোপুরি নিজের বলাও কঠিন।

## ডিজাইনারের কাছে কী চাইবেন

যিনিই আপনার লোগো ডিজাইন করুন না কেন, ছোট আর গোল জায়গার জন্য আলাদা একটা ভার্সন চাইবেন, আর এমন ফাইল চাইবেন যা থেকে পরে নিজেই যেকোনো সাইজ বানানো যায়।

logocontest.bd-তে কনটেস্ট চালালে ব্রিফেই দরকারি অপশনগুলো আছে:

- **লোগোটি কোথায় ব্যবহার করবেন?** অংশে **ফেসবুক / ইনস্টাগ্রাম** টিক দিন, যাতে ডিজাইনাররা বোঝেন লোগোকে ছোট সাইজেও কাজ করতে হবে।
- **যা যা লাগবে** অংশে প্রোফাইল ছবির জন্য **শুধু আইকন** বা **শর্ট লোগো**, আর হালকা-গাঢ় ব্যাকগ্রাউন্ডের জন্য **কালার, সাদা ও কালো ভার্সন** টিক দিন।
- **শর্তাবলি** অংশে **ছোট করলেও সহজে পড়া যায়** টিক দিন।
- **অন্যান্য শর্ত** ঘরে লিখে দিতে পারেন: "ফেসবুক প্রোফাইল ছবির জন্য সলিড ব্যাকগ্রাউন্ডে আইকনের একটি চৌকো PNG-ও দেবেন, আর প্রতিটি আইডিয়া ফেসবুক পেজের মকআপে দেখাবেন।"

প্রতিটি লোগো কনটেস্টের বিজয়ী মূল লোগোর AI, EPS, SVG, PDF, ট্রান্সপারেন্ট PNG আর JPG ফাইল বুঝিয়ে দেন, সাথে লোগোর পূর্ণ কপিরাইট। ফলে পরে আপনি বা যেকোনো ডিজাইনার মান না কমিয়েই ফেসবুকের নতুন সাইজ বানাতে পারবেন। পুরো ধাপগুলো জানতে পড়ুন [লোগো কনটেস্ট কীভাবে কাজ করে](/how-it-works), আর এখনকার প্যাকেজ দেখতে [লোগো ডিজাইনের দাম](/logo-design-price) পেজটি দেখুন।

বিজয়ী বাছার আগে পছন্দের ডিজাইনগুলো [AI লোগো চেকার](/logo-checker) দিয়ে যাচাই করে নিতে পারেন। এটি ছবি দিয়ে ওয়েবে খুঁজে দেখে কাছাকাছি দেখতে অন্য কোনো লোগো আছে কি না, logocontest.bd-এর কনটেস্টে আগে জমা পড়া লোগোর সাথেও মিলিয়ে দেখে, আর ফন্টও চেক করে। ফলাফলটাকে একটা গবেষণা রিপোর্ট হিসেবে নিন, আইনি নিশ্চয়তা হিসেবে নয়।

