## ফেসবুকে লোগো কেন এত ছোট আর গোল দেখায়

একটু ভাবুন, কাস্টমার আপনার লোগো আসলে কোথায় দেখেন। খুব কম মানুষই পেজে ঢুকে বড় হেডারটা খেয়াল করেন। বেশিরভাগ মানুষ লোগো দেখেন নিউজফিড স্ক্রল করার সময় পেজের নামের পাশে ছোট্ট একটা গোল ছবিতে, কমেন্টের রিপ্লাইয়ে, মেসেঞ্জারের চ্যাটে বা নোটিফিকেশনে। সেই সাইজে গোল ছবিটা প্রায় একটা নখের সমান।

ধরুন, মিরপুরের একটি শাড়ির পেজের লোগো হলো লম্বা, প্যাঁচানো হরফে দোকানের পুরো নাম, নিচে একটা স্লোগান। ফোনে সেটা স্রেফ রঙিন একটা ছোপ হয়ে যায়। গতকাল যে কাস্টমার ঈদ কালেকশনের পোস্ট দেখেছিলেন, আজ তিনি পেজটা চিনতে পারেন না, কারণ গোল ছবিতে মনে রাখার মতো পরিষ্কার কিছু নেই।

সমাধান নতুন লোগো নয়, বরং ছোট গোল জায়গার জন্য লোগোর সঠিক **ভার্সন**: সাধারণত শুধু আইকন, নামের প্রথম অক্ষর বা ছোট নাম, মোটা শেপ আর কম ডিটেইল।

ছোট একটা পরীক্ষা করে দেখুন: ফোনে লোগোটা কমেন্টের পাশের ছবির মতো ছোট করুন, তারপর হাত লম্বা করে ফোনটা দূরে ধরুন। তখনো যদি বোঝা যায় এটা কী, তাহলে ফেসবুকে কাজ করবে।

