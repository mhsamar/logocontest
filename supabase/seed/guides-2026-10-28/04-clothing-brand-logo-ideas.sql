## Instagram and Facebook: the tiny circle test

For many clothing brands in Bangladesh, the Facebook page and Instagram profile are the shop. Your logo appears as a small circle next to every post: can someone recognise it at fingertip size?

- **Use the monogram for the profile picture.** A long wordmark becomes hard to read in a small circle.
- **Leave space around the edges.** Profile pictures show as a circle, so ask for a square version with the mark centred.
- **Get white and black versions** for product photos and reels on light and dark backgrounds; the **Colour, white and black versions** extra in the brief covers this.
- **Keep it consistent** on Facebook, Instagram, labels and parcels, so customers recognise your parcel at the door.

