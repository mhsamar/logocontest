## FAQ

### What kind of logo is best for a clothing brand?

For most new clothing brands, a clean wordmark with a matching monogram. The wordmark builds the name; the monogram fits labels, buttons and profile pictures.

### What size should my logo be for a Facebook or Instagram profile picture?

Use a square version with the monogram or icon centred and space around it, since it will show as a small circle. Exact pixel sizes change, so check each platform's help page.

### Should a saree or Panjabi brand use a Bangla logo?

It often helps, especially for festive and handloom collections. Many brands pair a Bangla wordmark with an English version for Instagram and online search. Ask designers to keep the Bangla letters clear at small sizes.

