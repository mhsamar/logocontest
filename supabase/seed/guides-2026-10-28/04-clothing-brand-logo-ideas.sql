## লেবেল, হ্যাং ট্যাগ, প্যাকেজিং আর এমব্রয়ডারির সীমা

আপনার লোগো তৈরি হবে সুতা, ফয়েল আর কালি দিয়ে, শুধু পিক্সেলে নয়, আর প্রতিটা পদ্ধতির কিছু সীমা আছে।

- **বোনা কলার লেবেল:** খুব সরু রেখা বা খুব ছোট লেখা বোনা লেবেলে প্রায়ই পরিষ্কার আসে না, অথচ মোটা, সহজ অক্ষর ঠিকঠাক বোনা যায়।
- **হ্যাং ট্যাগ:** খাকি কার্ডে এক রঙের লোগো পরিপাটি দেখায়; ফয়েল স্ট্যাম্পিং বা এমবসিংয়েও পরিষ্কার আকৃতি লাগে।
- **প্যাকেজিং:** কুরিয়ারের পলি ব্যাগ, গিফট বক্স আর সিল করার স্টিকারই প্রায়ই এফ-কমার্সের ক্রেতা প্রথম দেখেন, আর মনোগ্রামের একটা স্টিকার পার্সেলকে বিশেষ করে তোলে।

এমব্রয়ডারিতে বাড়তি যত্ন লাগে:

1. সরু রেখা আর ছোট অক্ষর সেলাইয়ে ঝাপসা হয়ে যেতে পারে, তাই এমব্রয়ডারির কারিগরকে জিজ্ঞেস করুন অক্ষর সবচেয়ে ছোট কত হলে ভালো আসে।
2. গ্রেডিয়েন্ট, শ্যাডো আর ছবির মতো ইফেক্ট সেলাইয়ে ভালো আসে না; সমান রং ভালো আসে।
3. প্রতিটা সুতার রং কাজ বাড়ায়, তাই কম রঙের ডিজাইন সাধারণত বেশি পরিপাটিভাবে এমব্রয়ডারি হয়।
4. অক্ষরের ভেতরের ছোট বন্ধ জায়গা, যেমন "a" বা "e"-এর ভেতরটা, সুতায় ভরে যেতে পারে, তাই খোলা, চওড়া অক্ষর ভালো সেলাই হয়।

ব্রিফে "এক রঙেও কাজ করে (সাদা-কালো)" আর "ছোট করলেও সহজে পড়া যায়" শর্ত দুটো দিলে ডিজাইনাররা এটা মাথায় রাখবেন।

কনটেস্টের বিজয়ী চূড়ান্ত ফাইল দেন AI, EPS, SVG, PDF, PNG আর JPG ফরম্যাটে। লেবেলের কারখানা আর এমব্রয়ডারির দোকান সাধারণত ভেক্টর ফাইল (AI, EPS, SVG বা PDF) চায়।

## ইনস্টাগ্রাম আর ফেসবুক: ছোট্ট গোল ছবির পরীক্ষা

বাংলাদেশে অনেক পোশাকের ব্র্যান্ডের কাছে ফেসবুক পেজ আর ইনস্টাগ্রাম প্রোফাইলই আসল দোকান। প্রতিটা পোস্টের পাশে আপনার লোগো দেখা যায় ছোট্ট একটা গোল ঘরে, তাই নিজেকে জিজ্ঞেস করুন: আঙুলের ডগার সমান আকারে দেখেও কি কেউ চিনতে পারবে?

- **প্রোফাইল ছবিতে মনোগ্রাম দিন।** লম্বা ওয়ার্ডমার্ক ছোট গোল ঘরে পড়াই কঠিন।
- **চারপাশে জায়গা রাখুন।** প্রোফাইল ছবি গোল আকারে দেখায়, তাই মাঝখানে চিহ্ন রেখে একটা চৌকো ভার্সন চেয়ে নিন।
- **সাদা আর কালো ভার্সন রাখুন,** যাতে পণ্যের ছবি আর রিলসের হালকা-গাঢ় ব্যাকগ্রাউন্ডে লোগো বসানো যায়; ব্রিফের বাড়তি অপশন **কালার, সাদা ও কালো ভার্সন** ঠিক এই কাজটাই করে।
- **সব জায়গায় একই রাখুন:** ফেসবুক, ইনস্টাগ্রাম, লেবেল আর পার্সেলে, যাতে পোস্টে দেখা ক্রেতা দরজায় আসা পার্সেলটাও চিনতে পারেন।

## পোশাকের ব্র্যান্ডের লোগোর ব্রিফ কীভাবে লিখবেন

logocontest.bd-তে বাংলা বা ইংরেজিতে কয়েকটা সহজ প্রশ্নের উত্তর দেন, পুরস্কার ঠিক করেন, আর সারা বাংলাদেশের ডিজাইনাররা আইডিয়া পাঠাতে পারেন।

1. লোগোতে যেভাবে চান, ঠিক সেভাবে ব্র্যান্ডের নাম লিখুন। মনোগ্রামের জন্য কোন অক্ষর চান, তা **অন্যান্য শর্ত** ঘরে লিখুন।
2. ব্যবসার ধরন হিসেবে **ফ্যাশন ও পোশাক** বাছুন, আর লিখুন কী বিক্রি করেন ও আপনার ক্রেতা কারা।
3. **ওয়ার্ডমার্ক** আর **লেটারমার্ক**-এর মতো স্টাইল বাছুন, আর স্লাইডারে ঠিক করুন সাদামাটা না বিস্তারিত, আধুনিক না ক্লাসিক, মজাদার না গম্ভীর।
4. রং বাছুন, অথবা **ডিজাইনাররা বেছে নিক** অপশনে টিক দিন।
5. লোগো কোথায় ব্যবহার হবে তাতে টিক দিন, যেমন **মার্চেন্ডাইজ (টি-শার্ট, মগ)**, **প্যাকেজিং**, **প্রিন্ট (কার্ড, প্যাড)** আর **ফেসবুক / ইনস্টাগ্রাম**।
6. পছন্দের লেবেল বা ট্যাগের মতো উদাহরণ, কিংবা বর্তমান লোগো থাকলে আপলোড করুন।

কনটেস্ট চলার সময় স্টার আর মন্তব্য দিয়ে ডিজাইনারদের পথ দেখান, তারা উন্নত ভার্সন পাঠাতে পারেন। বিজয়ী বাছার পর চূড়ান্ত ফাইল অনুমোদনের আগে পরিবর্তন চাইতে পারবেন, আর লোগোর পূর্ণ কপিরাইট আপনাকে হস্তান্তর করা হয়। প্রতিটা ধাপ জানতে পড়ুন [কীভাবে কাজ করে](/how-it-works), আর এখনকার প্যাকেজ দেখুন [লোগো ডিজাইনের দাম](/logo-design-price) পেজে।

