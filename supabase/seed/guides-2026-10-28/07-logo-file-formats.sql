## ছয়টি লোগো ফাইল ফরম্যাট, একে একে

### AI (Adobe Illustrator)

AI ফাইল হলো Adobe Illustrator-এ বানানো ডিজাইনারের মূল (সোর্স) ফাইল, যেটা এডিট করা যায়। এতে লেয়ার, শেপ আর রং সব আলাদা থাকে, তাই পরে রং বদলাতে বা ঈদের জন্য বিশেষ ভার্সন বানাতে চাইলে ডিজাইনারের এই ফাইলটাই লাগে। খেয়াল করুন: এখানে "AI" মানে Illustrator, আর্টিফিশিয়াল ইন্টেলিজেন্স নয়। logocontest.bd-তে AI দিয়ে বানানো লোগো নিষেধ; AI ফাইল শুধু Illustrator-এর ফরম্যাট।

### EPS

EPS একটা পুরোনো ভেক্টর ফরম্যাট, যেটা প্রেস আর অনেক ডিজাইন সফটওয়্যার এখনো নেয়। প্রেস বা ব্যানারের দোকান "ভেক্টর ফাইল দেন" বললে EPS দেওয়া নিরাপদ।

### SVG

SVG হলো ওয়েবের ভেক্টর ফরম্যাট। ফাইল ছোট, যেকোনো স্ক্রিনে শার্প থাকে, আর ওয়েবসাইট বা অনলাইন শপের হেডারে লোগোর জন্য এটাই সবচেয়ে ভালো। ভিনাইল কাটিং বা খোদাইয়ের অনেক দোকানও SVG থেকে কাজ করতে পারে।

### PDF

প্রায় সব ফোন আর কম্পিউটারে PDF খোলে, তাই ইমেইল বা WhatsApp-এ প্রেসে পাঠানোর জন্য এটাই সবচেয়ে সহজ। ভেক্টর ডিজাইন থেকে সেভ করা PDF ভেক্টরের মান ধরে রাখে, তাই প্রিন্টের জন্য ভালো।

### PNG (ট্রান্সপারেন্ট)

PNG একটা র‍্যাস্টার ফরম্যাট, যাতে **ট্রান্সপারেন্ট ব্যাকগ্রাউন্ড** রাখা যায়, মানে লোগোর পেছনে সাদা বাক্স থাকে না। এটা স্ক্রিনের কাজে লাগান: ফেসবুক পোস্ট, ভিডিও, প্রেজেন্টেশন, বা কোনো ছবির ওপরে লোগো বসাতে। পিক্সেলে তৈরি বলে বড় প্রিন্টের জন্য এটা ঠিক ফাইল নয়।

### JPG

JPG-ও র‍্যাস্টার, কিন্তু ট্রান্সপারেন্ট হয় না; লোগো সবসময় একটা সাদা বা রঙিন বাক্সের ওপর থাকে। ফাইল ছোট আর সব জায়গায় খোলে, তাই দ্রুত শেয়ার করতে বা কোনো ডকুমেন্টে বসাতে সুবিধা। তবে JPG-এর কম্প্রেশনে কিনারা নরম হয়ে যায়, তাই যেখানে লোগো একদম পরিষ্কার দেখাতে হবে, সেখানে এটা এড়িয়ে চলুন।

