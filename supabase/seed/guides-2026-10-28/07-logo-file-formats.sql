## প্রশ্নোত্তর

### SVG, PNG আর AI-এর মধ্যে পার্থক্য কী?

SVG আর AI ভেক্টর ফাইল, যেকোনো সাইজে বড় করা যায়: SVG ওয়েবসাইটের জন্য, আর AI হলো Illustrator-এর এডিট করার মূল ফাইল। PNG স্ক্রিনের জন্য পিক্সেলের ছবি, এতে ট্রান্সপারেন্ট ব্যাকগ্রাউন্ড রাখা যায়, কিন্তু বড় করলে ঝাপসা হয়।

### প্রিন্টের জন্য কোন লোগো ফাইল ফরম্যাট সবচেয়ে ভালো?

ভেক্টর ফাইল: PDF, EPS বা AI। অনেক প্রেস PDF বা EPS নেয়, তাই আপনার প্রেস কোনটা চায়, জিজ্ঞেস করে নিন।

### PNG বা JPG লোগোকে কি ভেক্টর বানানো যায়?

নাম বদলে বা কনভার্ট করে নয়, আর অটোমেটিক ট্রেসিংয়ে সাধারণত ফল ভালো হয় না। একজন ডিজাইনারকে ভেক্টর শেপে নতুন করে আঁকতে হয়, তাই শুরু থেকেই ভেক্টর ফাইল নিয়ে রাখা ভালো।

### আমার কাছে Adobe Illustrator নেই। ফাইলগুলো কি ব্যবহার করতে পারব?

হ্যাঁ। PNG, JPG আর PDF যেকোনো ফোন বা কম্পিউটারে খোলে, আর SVG খোলে ওয়েব ব্রাউজারে। Inkscape-এর মতো ফ্রি সফটওয়্যারে SVG আর PDF খোলা যায়, অনেক সময় EPS আর AI-ও। AI ফাইলটা ডিজাইনারের জন্য রেখে দিন।

