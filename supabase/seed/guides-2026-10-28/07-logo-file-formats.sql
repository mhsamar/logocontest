## FAQ

### What is the difference between SVG, PNG and AI?

SVG and AI are vector files that scale to any size: SVG is made for websites, and AI is the editable Illustrator source. PNG is a pixel image for screens that can have a transparent background, but it blurs when you enlarge it.

### Which logo file format is best for printing?

A vector file: PDF, EPS or AI. Many presses accept PDF or EPS, so ask your printer which one they prefer.

### Can I turn a PNG or JPG logo into a vector file?

Not by renaming or converting it, and automatic tracing usually gives rough results. A designer has to redraw it as vector shapes, which is why it is worth getting vector files from the start.

### I don't have Adobe Illustrator. Can I still use my logo files?

Yes. PNG, JPG and PDF open on any phone or computer, and SVG opens in a web browser. Free programs such as Inkscape can open SVG and PDF files, and often EPS and AI files too. Keep the AI file for designers.

### Is the AI file made by artificial intelligence?

No. AI is the file type of Adobe Illustrator. On logocontest.bd, every logo must be original, human-made work.

