  $g7$Your logo comes in several **logo file formats** because each job needs a different kind of file. In short: AI, EPS, SVG and PDF are **vector** files that can be printed at any size without losing quality, so they go to printers and signboard makers. PNG and JPG are **pixel (raster)** images for screens, and of these two, only PNG can have a transparent background. This guide explains each format, the real difference between SVG, PNG and AI, which file to use where, and what a logocontest.bd winner hands over.

## Vector vs raster: the one idea that explains everything

A **raster** image, such as a PNG or JPG, is a grid of tiny coloured squares called pixels. It looks fine at the size it was made for. Stretch it bigger and the squares show: edges turn blurry or jagged.

A **vector** file, such as AI, EPS, SVG or a vector PDF, stores the logo as shapes and lines described by maths. The computer redraws those shapes at whatever size you need, so the same file works on a visiting card and on a shop signboard several feet wide.

Here is how this goes wrong in real life. A bakery owner downloads the logo from their Facebook page, sends it on WhatsApp to a signboard maker, and asks for a big acrylic board. The file is only a few hundred pixels wide, so the board comes out fuzzy, or the signboard maker has to redraw the logo by hand and charges extra. With a vector file, the job is simple.

Two rules follow from this:

- Keep the vector files as your master copy, and make PNG or JPG copies from them when you need them.
- Renaming a JPG, or using "save as" to turn it into SVG or AI, does not make it a vector. A real vector logo has to be drawn as vector shapes.

## The six logo file formats, one by one

### AI (Adobe Illustrator)

The AI file is the designer's editable source file, made in Adobe Illustrator. It keeps the layers, shapes and colours, so it is the file a designer needs if you ever want changes, such as a new colour or a special version for Eid. Note that "AI" here means Illustrator, not artificial intelligence. On logocontest.bd, AI-generated logos are not allowed; the AI file is simply the Illustrator format.

### EPS

EPS is an older vector format that print shops and many design programs still accept. When a printing press or banner maker asks for "the vector file", EPS is a safe answer.

### SVG

SVG is the vector format for the web. It is small, stays sharp on every screen, and is the best choice for the logo in your website header or online shop. Many vinyl-cutting and engraving shops can also work from it.

### PDF

Almost every phone and computer can open a PDF, which makes it the easiest file to send to a printing press by email or WhatsApp. A PDF saved from the vector artwork keeps its vector quality, so it is good for printing.

### PNG (transparent)

PNG is a raster format that can have a **transparent background**, so there is no white box behind the logo. Use it on screens: Facebook posts, a video, a presentation, or on top of a photo. Because it is made of pixels, it is not the right file for large printing.

### JPG

JPG is a raster format with no transparency, so the logo always sits on a white or coloured box. Files are small and open everywhere, handy for quick sharing or a document. JPG compression softens edges, so avoid it where the logo needs to look crisp.

## Which logo file to use where

- **Visiting cards, letterheads, memo pads, stickers:** PDF or EPS. Ask the press for a printed proof first, as colours on paper can differ from the screen.
- **Signboards, banners, PVC, acrylic letters, neon:** a vector file (EPS, AI, PDF or SVG). Never a PNG taken from Facebook.
- **Facebook profile picture, posts and cover:** PNG. Use a square version of the icon for the round profile picture.
- **Website and online shop:** SVG for the logo, with a PNG as a backup. Use the icon alone for the small browser tab icon (favicon).
- **T-shirts, caps and mugs:** printers usually ask for a vector file (EPS, AI or PDF) or a large transparent PNG. Embroidery shops usually turn the logo into their own stitch file, so a simple one-colour version helps.
- **Rubber stamps and seals:** the black, one-colour version as a vector file.
- **Videos and YouTube intros:** a transparent PNG, or SVG for a motion designer.
- **Word files, invoices and price lists:** PNG, or JPG on a white page.
- **A new designer who will edit the logo:** the AI file, plus the names of the fonts used.

