- **নতুন কোনো ডিজাইনার, যিনি লোগো এডিট করবেন:** AI ফাইল, সাথে ব্যবহার করা ফন্টের নাম।

## শুধু ফরম্যাট নয়, লোগোর ভার্সনও লাগে

ফরম্যাটের পাশাপাশি লোগোর কয়েকটা ভার্সনও দরকার। গাঢ় নীল লোগো গাঢ় রঙের ফেসবুক কভারে হারিয়ে যায়, আর রাবার স্ট্যাম্পে একটাই রং ছাপা যায়। তাই ডিজাইনাররা সাধারণত কালার, সাদা আর কালো ভার্সন দেন, আর প্রোফাইল ছবি বা অ্যাপের মতো ছোট জায়গার জন্য প্রায়ই শর্ট লোগো বা আইকন।

logocontest.bd-তে এগুলো ব্রিফের **যা যা লাগবে** অংশেই বেছে নেওয়া যায়: শুধু আইকন, শর্ট লোগো, কালার, সাদা ও কালো ভার্সন, আর অ্যাপ আইকন সাইজ। আপনি যা টিক দেবেন, বিজয়ী মূল ফাইলের সাথে সেগুলোও দেবেন।

## logocontest.bd-এর বিজয়ী কোন কোন ফাইল দেন

লোগো কনটেস্টে বিজয়ী বাছার পর ফাইল হস্তান্তর হয় সাইটের মাধ্যমেই:

- **ছয়টি ফাইল, সবগুলোই বাধ্যতামূলক:** AI, EPS, SVG, PDF, ট্রান্সপারেন্ট PNG আর JPG।
- AI আর EPS ফাইল বড় হয়, তাই বিজয়ী এগুলো Google Drive লিংক হিসেবে দেন, শেয়ারিং থাকে "Anyone with the link can view"। বাকি চারটি সাইটে আপলোড করা হয়। হাতে পাওয়ার পর Drive-এর ফাইল দুটোর একটা কপি নিজের কাছেও রেখে দিন।
- ডিজাইনারকে ব্যবহার করা **ফন্ট**-এর নামও লিখে দিতে বলা হয়, যাতে পরে যে কেউ একই রকম লেখা মেলাতে পারেন।
- ব্রিফে বাড়তি যা টিক দিয়েছিলেন, সেগুলো আসে অতিরিক্ত ফাইল হিসেবে।
- অনুমোদনের আগে ফাইলগুলো দেখে পরিবর্তন চাইতে পারেন। আপনি অনুমোদন না করা পর্যন্ত পেমেন্ট আটকে রাখা হয়, আর লোগোর পূর্ণ কপিরাইট আপনার কাছে আসে।
- অনুমোদিত ফাইল আপনার অ্যাকাউন্টে থাকে, যেকোনো সময় ডাউনলোড করা যায়।

